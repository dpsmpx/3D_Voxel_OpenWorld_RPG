#pragma once
#include "../core/types.h"
#include "../ecs/registry.h"
#include "attributes.h"

namespace progression {

/// Проверка и списание ресурсов. Возвращает true, если удалось
/// списать — иначе атакующее действие блокируется.
bool tryConsumeMana(ecs::Registry& reg, ecs::Entity e, f32 amount);
/// Списывает выносливость, если её хватает.
///
/// Списанная выносливость оставляет после себя утомление — см.
/// FATIGUE_PER_STAMINA. Потому и нет отдельного «потратить без
/// утомления»: такого действия в игре не бывает.
/// @return false и ничего не списано, если выносливости недостаточно
bool tryConsumeStamina(ecs::Registry& reg, ecs::Entity e, f32 amount);

/// Принудительное списание без проверки (для отладки и эффектов).
void consumeMana(ecs::Registry& reg, ecs::Entity e, f32 amount);
/// Списывает выносливость безусловно, обрезая по нулю.
/// Для действий, которые нельзя отменить (получение урона).
void consumeStamina(ecs::Registry& reg, ecs::Entity e, f32 amount);

/// Мгновенное восстановление (для зелий в Phase 12).
void restoreMana(ecs::Registry& reg, ecs::Entity e, f32 amount);
/// Восстанавливает выносливость, не превышая максимум.
void restoreStamina(ecs::Registry& reg, ecs::Entity e, f32 amount);
/// Восстанавливает здоровье, не превышая максимум.
void restoreHealth(ecs::Registry& reg, ecs::Entity e, f32 amount);

/// ---- Утомление ----
///
/// Доля выносливости, которую утомление ОТНИМАЕТ при полном значении.
/// Половина: вымотанный не обессилен вовсе, но бежит вдвое меньше.
constexpr f32 FATIGUE_CAP_LOSS = 0.5f;

/// Сколько секунд без нагрузки, прежде чем утомление начнёт спадать.
/// Мгновенный отдых в разгар боя обесценил бы саму идею.
constexpr f32 FATIGUE_REST_DELAY = 3.f;

/// Сколько секунд без нагрузки, прежде чем ПОЙДЁТ реген выносливости.
///
/// Секунда, а не три: это не отдых, а «перестал тратить». Без этой
/// паузы бег не тратил бы ничего: реген даёт одиннадцать в секунду,
/// бег берёт двенадцать, и шкала убывала бы по единице — восемьдесят
/// секунд до дна вместо восьми.
constexpr f32 STAMINA_REGEN_DELAY = 1.f;

/// За сколько секунд отдыха утомление спадает от полного до нуля.
constexpr f32 FATIGUE_RECOVER_SEC = 25.f;

/// Сколько утомления оставляет после себя единица потраченной
/// выносливости.
///
/// Правило одно на всё: бег, рывок, удар, полученный удар. Считать
/// утомление отдельно в каждом из этих мест означало бы завести
/// четыре правила, которые разойдутся молча.
///
/// 1/600: полминуты непрерывного бега или затяжная драка на полсотни
/// ударов выматывают заметно, а короткая стычка почти не
/// сказывается — и не должна.
constexpr f32 FATIGUE_PER_STAMINA = 1.f / 600.f;

/// Накопить утомление. Значение зажимается в [0, 1].
///
/// Зовут оба источника нагрузки: бег (player) и удар (combat).
/// Заодно сбрасывает отсчёт отдыха — отдыхом считается время БЕЗ
/// нагрузки, а не время с последнего вдоха.
void addFatigue(ecs::Registry& reg, ecs::Entity e, f32 amount);

/// Потолок выносливости с учётом утомления, в тех же единицах, что и
/// Stamina::max. Без компонента Fatigue — просто max.
///
/// Потолок опускается, а не max: max — производная характеристика,
/// её каждый кадр пересчитывает прогрессия, и запись туда стёрлась
/// бы на следующем же кадре.
f32 staminaCeiling(ecs::Registry& reg, ecs::Entity e);

/// Хелперы для боевой системы — получить множители расхода
/// с учётом производных характеристик.
f32 manaCostMult(ecs::Registry& reg, ecs::Entity e);
/// Множитель расхода выносливости от атрибутов и навыков.
/// @return 1.0 без бонусов, меньше — расход снижен
f32 staminaCostMult(ecs::Registry& reg, ecs::Entity e);

} // namespace progression
