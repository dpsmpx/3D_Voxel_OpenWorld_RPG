/**
 * @file crashlog.h
 * @brief Журнал и отчёт о падении в файл, доступный без adb.
 *
 * На телефоне без подключённого отладчика logcat приложения прочитать
 * нельзя: система отдаёт приложению только его собственные логи, а
 * Termux — это другое приложение. Поэтому игра пишет журнал сама:
 *
 *   1. во внутренний каталог — он есть всегда;
 *   2. в /sdcard/Android/media/<пакет>/ — оттуда файл читается из
 *      Termux после termux-setup-storage, в отличие от Android/data,
 *      закрытого начиная с Android 11.
 *
 * Плюс обработчики сигналов: при падении в файл попадают номер
 * сигнала, адрес обращения и стек вызовов. Без этого «мгновенный
 * вылет» не отличить от «чёрного экрана».
 */
#pragma once

namespace crash {

/// Открывает журнал и ставит обработчики сигналов. Вызывать первой
/// строкой android_main: всё, что залогировано раньше, пропадёт.
/// Пути берутся из ANativeActivity; любой может быть nullptr.
void init(const char* internalDataPath, const char* externalDataPath);

/// ---- Выключатель журнала ----
///
/// Ведение журнала стоит двух системных вызовов на строку (logcat и
/// файл) и растёт в размере всю сессию. Игроку, который просто
/// играет, он не нужен вовсе, поэтому его можно выключить целиком —
/// и logcat, и файл.
///
/// Флаг читается КАЖДЫМ макросом LOG*, поэтому он открытый, а
/// проверка — inline: вызов через границу трансляции на каждую
/// строку стоил бы дороже самой проверки.
///
/// По умолчанию журнал ВЕДЁТСЯ: до чтения settings.cfg успевает
/// произойти половина запуска, и молчать в это время нельзя —
/// именно там и ломается то, что ломается.
extern bool gEnabled;
inline bool enabled() { return gEnabled; }

/// Включить или выключить журнал. Сам переход записывается в файл:
/// иначе оборвавшийся журнал не отличить от упавшей игры.
void setEnabled(bool on);

/// Добавляет строку в журнал. Вызывается из макросов LOG*.
/// Безопасна до init(): просто ничего не делает.
/// При выключенном журнале не делает ничего тоже.
void write(char level, const char* fmt, ...) __attribute__((format(printf, 2, 3)));

/// То же, но пишется ВСЕГДА, даже при выключенном журнале.
///
/// Для того, после чего программа не продолжится. Выключить журнал —
/// значит отказаться от рутинных записей, а не от посмертной
/// записки: иначе настройка «не вести лог» тихо отключала бы
/// единственный способ узнать причину падения.
void writeFatal(const char* fmt, ...) __attribute__((format(printf, 1, 2)));

/// Отметка о пройденном этапе запуска. Последняя отметка в файле —
/// то место, где всё оборвалось.
///
/// Саму отметку запоминает и при выключенном журнале: в файл она не
/// пойдёт, но отчёт о падении её печатает, а он пишется всегда.
void step(const char* name);

/// Куда пишется журнал (для вывода в логе). Пустая строка, если никуда.
const char* logPath();
const char* sharedLogPath();

} // namespace crash
