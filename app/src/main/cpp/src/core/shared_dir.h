/**
 * @file shared_dir.h
 * @brief Каталоги, из которых файл видят ДРУГИЕ программы.
 */
#pragma once
#include "types.h"

namespace sys {

/// Длина одного пути. Столько же, сколько отводит под них журнал.
constexpr usize SHARED_PATH_CAP = 512;

/// Имя пакета из пути вида `/data/data/<пакет>/...`,
/// `/data/user/0/<пакет>/...` или `.../Android/data/<пакет>/files`.
///
/// Пустая строка, если не разобрать. Имя пакета нужно затем, что
/// общий каталог называется по нему, а спросить его у системы из
/// нативного кода нечем — только вывести из путей, которые она дала.
void packageFromPath(const char* path, char* out, usize outSize);

/// Куда писать файл, чтобы его нашли снаружи.
///
/// Каталог `Android/data` с Android 11 закрыт для других приложений,
/// а `Android/media` — нет, поэтому первым идёт именно он. Список, а
/// не один путь: на externalDataPath полагаться нельзя (система
/// оставляет его пустым, если хранилище не смонтировано на момент
/// запуска), а корень внешнего хранилища на разных прошивках зовётся
/// по-разному.
///
/// Заполняет до `cap` путей в порядке предпочтения, возвращает
/// сколько заполнил. Существование каталогов НЕ проверяется: их
/// создаёт тот, кто пишет.
u32 sharedDirCandidates(const char* internalDataPath,
                        const char* externalDataPath,
                        char out[][SHARED_PATH_CAP], u32 cap);

} // namespace sys
