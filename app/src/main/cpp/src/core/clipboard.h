/**
 * @file clipboard.h
 * @brief Буфер обмена Android из нативного кода.
 */
#pragma once
#include "types.h"
#include <string>

struct ANativeActivity;

namespace sys {

/// Кладёт текст в буфер обмена.
///
/// Нужно ровно за одним: журнал игры лежит файлом на устройстве, и
/// чтобы его прочитать, приходится идти в Termux. Буфер обмена
/// избавляет от этого похода — текст сразу вставляется куда угодно.
///
/// Возвращает false, если не вышло, и пишет в журнал причину. Не
/// выйти может по-разному: приложение уже не на переднем плане (часть
/// прошивок молча отказывает фоновым), строка не влезла в транзакцию
/// Binder, виртуальная машина недоступна. Ни один из этих случаев не
/// должен ронять выход из игры, поэтому все исключения Java гасятся
/// здесь же.
bool copyToClipboard(ANativeActivity* activity, const char* text);

/// Кладёт в буфер обмена содержимое файла.
///
/// Транзакция Binder ограничена примерно мегабайтом на весь процесс,
/// а журнал длинной сессии перерастает его легко. Поэтому большой
/// файл берётся не целиком: начало (там условия запуска — устройство,
/// разрешение, режим показа) плюс хвост (там то, на чём всё
/// кончилось), а между ними отметка о пропуске.
bool copyFileToClipboard(ANativeActivity* activity, const char* path);

/// Готовит текст журнала для буфера: целиком, если файл невелик, иначе
/// начало плюс хвост с отметкой о пропуске между ними.
///
/// Отдельно от отправки, потому что проверять надо именно это. Сама
/// отправка — это JNI, её на хосте не выполнить; а вот срезка по
/// смещениям — обычный код, и ошибка в ней даёт не отказ, а мусор в
/// буфере, который заметишь только когда он понадобится.
///
/// Пустая строка, если файла нет или он пуст.
std::string clipboardTextFromFile(const char* path);

/// Сколько байт файла кладём в буфер обмена и сколько из них отдаём
/// началу. Числа с запасом: предел транзакции — около мегабайта на
/// весь процесс, и занимать его целиком ради журнала неразумно.
constexpr usize CLIPBOARD_MAX_BYTES  = 256 * 1024;
constexpr usize CLIPBOARD_HEAD_BYTES = 32 * 1024;

} // namespace sys
