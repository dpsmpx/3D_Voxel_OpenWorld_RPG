/**
 * @file file_picker.h
 * @brief Системный выбор файла через активность Android.
 */
#pragma once
#include "types.h"
#include <string>

struct ANativeActivity;

namespace sys {

/// Открыть системный диалог выбора файла.
///
/// Возвращает false, если позвать активность не вышло вовсе: нет
/// виртуальной машины, нет метода, прошивка отказала. Сам ВЫБОР
/// приходит позже и не сюда — диалог модальный для пользователя, но
/// не для игры: игровой цикл продолжает крутиться.
///
/// Ответ забирают takePickedFile().
bool openWorldPicker(ANativeActivity* activity);

/// Забрать путь к выбранному файлу, если он уже выбран.
///
/// Пустая строка — ещё не выбран или выбор отменён. Забирается ОДИН
/// раз: второй вызов вернёт пустую строку, пока не выберут снова.
/// Иначе один выбор применился бы в каждом кадре подряд.
std::string takePickedFile();

/// Ждём ли мы сейчас ответа от диалога.
///
/// Нужно интерфейсу: пока диалог открыт, вторую кнопку жать
/// бессмысленно.
bool pickerPending();

} // namespace sys
