namespace physics {

struct MoveInput {
    glm::vec2 wishDir{0};
    /// Куда смотрит камера по горизонтали. Нужен рывку: стоя на
    /// месте, игрок жмёт рывок и ждёт, что его бросит ВПЕРЁД, а не
    /// оставит на месте за неимением направления движения.
    glm::vec2 faceDir{0, -1};
    bool      jumpPressed = false;
    bool      jumpHeld    = false;
    bool      sprint      = false;
    bool      crouch      = false;
    bool      dashPressed = false;
};

struct CharacterState {
    glm::vec3 position{0};
    glm::vec3 velocity{0};
    bool onGround = false;
    bool inWater  = false;
    bool inLava   = false;
    /// По пояс и глубже: середина тела в воде.
    ///
    /// Выталкивает только того, кто и правда плывёт. Раньше хватало
    /// мокрых ног: зайдя в лужу по щиколотку, игрок всплывал над ней
    /// — стоять в воде было нельзя вовсе, только плавать.
    bool waistDeep = false;
    /// Голова под водой.
    ///
    /// Уровень глаз читался и раньше — в переменную, которую не
    /// спрашивал никто: под водой в игре не менялось ничего, и
    /// «погружение» существовало ровно как факт, что ноги мокрые.
    bool submerged = false;
    /// Всплывает после нырка с высоты. Ушедшего под воду падением
    /// выносит к поверхности, пока он сам не решит грести или
    /// нырять: иначе упавший в озеро оставался бы висеть в толще,
    /// как нарочно нырнувший.
    bool surfacing = false;
    f32  coyoteTimer = 0.f;
    f32  jumpBufferTimer = 0.f;

    /// Подъём на ступень в процессе.
    ///
    /// Раньше подъёма «в процессе» не было: контроллер убеждался, что
    /// наверху свободно, и ОДНОЙ СТРОКОЙ переставлял игрока туда —
    /// `position.y += h`. С точки зрения физики верно, с точки зрения
    /// глаз — телепортация: камера скачком уезжала на полметра вверх.
    ///
    /// Теперь это состояние: игрок поднимается с ограниченной
    /// скоростью, кадр за кадром, пока не дойдёт до цели.
    bool stepping   = false;
    f32  stepTargetY = 0.f;
    f32  stepTimer   = 0.f;   ///< страховка от застревания в подъёме

    /// ---- Рывок ----
    ///
    /// Рывок — это скорость на короткое время, а не перенос позиции.
    /// Перенос пришлось бы проверять на проходимость самому и по
    /// дороге он бы протаскивал сквозь стены; скорость идёт через то
    /// же разрешение коллизий, что и обычный шаг, и упирается в стену
    /// сама.
    f32       dashTimer    = 0.f;   ///< сколько рывку осталось
    f32       dashCooldown = 0.f;   ///< сколько до следующего
    glm::vec2 dashDir{0, -1};       ///< куда рвём, XZ, единичный

    bool dashing() const { return dashTimer > 0.f; }

    /// ---- Падение ----
    ///
    /// Высота, которой стоит текущее падение: верх полёта, пониженный
    /// всем, что его гасило, — водой, мягкой опорой (physics/impact.h).
    /// Стоящий на опоре держит здесь свою высоту.
    f32 fallTopY = 0.f;
    /// Посадка в этот кадр: с какой высоты тело ударилось об опору —
    /// уже после мягкости опоры и воды. Ноль — посадки не было.
    f32 landingDrop = 0.f;
    /// Опора, проломленная в этот кадр (0 — ничего), и где она была.
    /// Блок уже убран из мира: осколки и звук — дело того, кто
    /// ведёт тело.
    u16        brokeBlock = 0;
    glm::ivec3 brokeCell{0};
};

class CharacterController {
public:
    CharacterController() = default;

    void update(world::ChunkManager& world, const MoveInput& input, f32 dt);

    CharacterState&       state()       { return state_; }
    const CharacterState& state() const { return state_; }

    /// Переставить тело. Падение начинается заново отсюда: иначе
    /// спасённый из-под мира или воскрешённый «падал» бы с места,
    /// откуда его забрали.
    void setPosition(const glm::vec3& p) {
        state_.position = p;
        state_.velocity = glm::vec3(0);
        state_.fallTopY = p.y;
    }
    void addImpulse(const glm::vec3& v)  { state_.velocity += v; }

    /// Параметры движения
    f32 walkSpeed       = 4.5f;
    f32 sprintSpeed     = 7.5f;
    f32 swimSpeed       = 3.0f;
    f32 jumpVelocity    = 9.0f;
    f32 gravity         = -28.0f;
    f32 maxFallSpeed    = -60.0f;
    /// ---- Вода ----
    ///
    /// Всплытие было безусловным: кто не держит клавишу, того тянет
    /// вверх с ускорением в двадцать два — то есть нырнуть было
    /// нельзя вовсе. Отпустил погружение — и тебя выбросило на
    /// поверхность.
    ///
    /// Теперь выталкивает только ТО, ЧТО НАД ВОДОЙ: пока голова
    /// снаружи, тело держится на плаву; ушёл под воду — и висишь,
    /// медленно погружаясь. Ровно так и плавают.
    f32 waterBuoyancy   = 22.0f;   ///< у поверхности
    /// Насколько тонет тот, кто под водой и ничего не жмёт.
    /// Медленно: это «висит в толще», а не «идёт ко дну».
    f32 waterSinkRate   = 1.2f;
    f32 waterDrag       = 3.0f;
    /// Скорость всплытия и погружения по нажатию.
    f32 swimRiseSpeed   = 3.5f;
    f32 swimDiveSpeed   = 3.5f;
    /// Быстрее этого в жидкости не тонут. Всё, что быстрее, — нырок
    /// с высоты, и его гасит глубина (BlockImpact::drag), а не
    /// первый же кадр в воде: иначе лужа по щиколотку ловила бы
    /// падение с любой высоты.
    f32 swimMaxFall     = 5.0f;
    f32 groundFriction  = 12.0f;
    f32 accelRate       = 45.0f;
    f32 airAccelFactor  = 0.35f;
    f32 coyoteTime      = 0.12f;
    f32 jumpBufferTime  = 0.15f;

    /// ---- Рывок ----
    /// 22 м/с за 0.18 с — это около четырёх блоков: расстояние, на
    /// котором рывок и правда уводит из-под удара, но не заменяет
    /// ходьбу.
    f32 dashSpeed       = 22.0f;
    f32 dashTime        = 0.18f;
    f32 dashCooldownTime = 1.2f;

    /// Phase 15
    ///
    /// Высоты автоматического подъёма здесь больше нет, и это не
    /// упрощение, а исправление. Поле `stepHeight` ничего не решало:
    /// подъём целится в ВЕРХ СЛЕДУЮЩЕГО БЛОКА, то есть поднимает на
    /// `floor(y) + 1 - y`, а это не больше единицы никогда. Проверка
    /// «не выше stepHeight» при значении 1.10 не срабатывала ни разу,
    /// и ручка, которая на вид ограничивала подъём, не ограничивала
    /// ничего. Именно такая ручка и прятала настоящую причину, пока
    /// её не сверили с кодом.
    ///
    /// Подъём ограничивают две настоящие проверки в tryStepUp: тело
    /// должно ПОМЕЩАТЬСЯ на новой высоте и иметь опору под ногами.
    /// Стена в два блока не берётся потому, что на высоте одного
    /// блока телу не хватает места, а не потому, что где-то записано
    /// число.
    f32 stepCheckDist   = 0.30f;   // насколько вперёд проверяем при step-up
    /// Скорость подъёма на ступень, блоков в секунду.
    ///
    /// Полметра за одну восьмую секунды: быстрее выглядит рывком,
    /// медленнее — будто игрок залипает в стене.
    f32 stepClimbSpeed  = 4.5f;
    /// Сколько подъём может длиться, прежде чем его бросят. Без
    /// предела застрявший в подъёме игрок висел бы без гравитации.
    f32 stepMaxTime     = 0.40f;
    bool enableStepUp   = true;
    bool enableSnapDown = true;
    f32 snapDownDist    = 0.35f;   // максимальная просадка для snap-to-ground
    f32 snapDownMaxVel  = 0.6f;    // если падаем медленнее — снапимся

    PlayerBox box;

private:
    CharacterState state_;
    void detectEnvironment(world::ChunkManager& world);
    /// Phase 15: возвращает true, если назначен автоматический подъём
    /// на один блок вверх.
    bool tryStepUp(world::ChunkManager& world,
                   const glm::vec3& moveDelta);
    /// Phase 15: если игрок стоит близко к земле и падает медленно —
    /// притягиваем вниз.
    void snapDown(world::ChunkManager& world, f32 dt);
    /// Счёт падения за кадр: сколько оно стоит, чем кончилась посадка,
    /// не проломлена ли опора.
    void settleFall(world::ChunkManager& world, bool startedOnGround,
                    f32 yBefore, f32 vyBefore);
    /// Сколько «вязкости» пересекли ступни, пройдя от fromY вниз до
    /// toY: сумма BlockImpact::drag по пройденной глубине.
    f32 liquidDepthCrossed(world::ChunkManager& world, f32 fromY, f32 toY) const;
    /// Блок, на котором тело стоит больше всего площадью ступней.
    bool supportUnder(world::ChunkManager& world, glm::ivec3& cell, u16& block) const;
};

} // namespace physics
