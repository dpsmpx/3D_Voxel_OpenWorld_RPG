#pragma once
#include "../core/types.h"
#include "../ecs/registry.h"
#include "../world/chunk_manager.h"
#include <glm/glm.hpp>

namespace items {

/// Брошенный батут, лежащий в мире.
///
/// Батут — сущность, а не блок. Блок занял бы целый воксель, и
/// прыгать пришлось бы С НЕГО, то есть сперва на него забраться.
/// Лежащая площадка не мешает ходьбе и срабатывает, когда на неё
/// наступают.
struct Trampoline {
    f32 lifeRemaining = 120.f;   ///< сколько лежит, секунд
    f32 bounce        = 15.f;    ///< скорость подброса, м/с
    f32 radius        = 0.9f;    ///< половина стороны площадки
    /// Задержка после срабатывания: без неё батут ловит игрока на
    /// первом же кадре подъёма и подбрасывает второй раз.
    f32 cooldown      = 0.f;
};

/// Высота площадки над блоком, на котором она лежит.
constexpr f32 TRAMPOLINE_PAD_H = 0.25f;

/// Бросить батут по направлению взгляда.
///
/// Траектории у броска нет: точка падения ищется лучом и опускается
/// до земли. Снаряд с гравитацией дал бы красивую дугу и непонятное
/// место приземления — а батут кидают ровно туда, куда собираются
/// прыгнуть.
///
/// @return созданная сущность; недействительная, если бросать некуда
ecs::Entity throwTrampoline(ecs::Registry& reg,
                            world::ChunkManager& world,
                            const glm::vec3& origin,
                            const glm::vec3& dir);

/// Отсчёт времени жизни и задержек. Истёкшие батуты убираются.
void updateTrampolines(ecs::Registry& reg, f32 dt);

/// Скорость подброса для стоящего в этой точке; 0 — батута под ним нет.
///
/// Точка — ступни. Срабатывание засчитывается, только если игрок и
/// правда опускается: подпрыгнув с батута и пролетая над ним вверх,
/// второй раз он не срабатывает.
f32 trampolineBounceAt(ecs::Registry& reg,
                       const glm::vec3& feet,
                       f32 verticalVelocity);

} // namespace items
