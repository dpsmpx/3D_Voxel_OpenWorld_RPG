/**
 * @file item_models.h
 * @brief Предметы: воксельные модели — как предмет выглядит в мире и на значке.
 */
#pragma once
#include "../core/types.h"
#include "../render/voxel_model.h"

namespace items {

/// Модель предмета: как он лежит на земле и как выглядит его значок.
///
/// Своя модель есть у каждого предмета реестра: у блока это блок в
/// миниатюре с узором своего материала (кольца на спиле, вкрапления
/// руды, швы кладки), у меча — клинок, гарда и рукоять, у зелья —
/// склянка своего цвета. Предмет без своей модели получил бы кубик
/// цвета редкости — таких нет, и за этим следит проверка.
///
/// Модели строятся один раз, при первом обращении. У пустого номера
/// (предмета нет в реестре) модель пустая.
const render::VoxelModel& itemModel(u16 itemId);

/// Есть ли у предмета своя модель, а не запасной кубик.
bool hasOwnModel(u16 itemId);

} // namespace items
