namespace npc {

/// Сколько обликов заготовлено на вид.
///
/// Оснастка строится один раз на (вид, облик) и живёт до выхода:
/// строить её на особь означало бы пересобирать иерархию каждый кадр
/// ради значений, которые не меняются.
///
/// Шестнадцать — не «побольше на всякий случай». При шести жителях в
/// деревне восьми обликов не хватает: пара совпадёт почти наверняка,
/// и деревня снова выглядит складом кукол.
constexpr u8 NPC_VARIANTS = 16;

/// Оснастка вида и облика. `seed` — из ecs::Appearance.
const entity::Rig& rigFor(u16 npcId, u32 seed);

/// Тот же выбор облика, что делает rigFor. Нужен спавнеру: длину шага
/// он берёт из ТОЙ ЖЕ оснастки, которую потом нарисует рендер.
u8 variantOf(u32 seed);

} // namespace npc
