#pragma once
#include "../core/types.h"
#include "terrain.h"
#include <glm/glm.hpp>

namespace world {

/// Состояние неба — то, что игрок назвал бы одним словом.
enum class Sky : u8 {
    Clear = 0,   ///< ясно
    Fair,        ///< переменная облачность
    Cloudy,      ///< облачно
    Overcast,    ///< пасмурно: неба не видно
    Rain,        ///< дождь
    Snow,        ///< снег
    Storm,       ///< ливень с ветром
    Count
};

const char* skyName(Sky s);

/// Циклон — область низкого давления, которая едет по миру.
///
/// Погода без циклонов сводится к «включился дождь, выключился
/// дождь»: она меняется вся сразу и везде одинаково. Циклон даёт
/// то, чего иначе взять неоткуда, — ПОГОДУ В МЕСТЕ: тучи приходят с
/// одной стороны, ветер заворачивает, дождь идёт полосой, и с холма
/// видно, что за рекой ещё светит солнце.
struct Cyclone {
    glm::vec2 center{0.f};   ///< где середина сейчас, в блоках
    f32       radius   = 0.f;///< блоков от середины до края
    f32       strength = 0.f;///< 0..1, уже с учётом возраста
    f32       age      = 0.f;///< 0..1 доля прожитого
    glm::vec2 drift{0.f};    ///< куда едет, блоков в секунду
};

/// Что творится в точке.
struct WeatherSample {
    f32       pressure = 0.f;  ///< 0 — ясно, 1 — середина глубокого циклона
    f32       cloud    = 0.f;  ///< доля неба, закрытая тучами
    f32       precip   = 0.f;  ///< сила осадков, 0..1
    bool      snow     = false;///< осадки идут снегом, а не дождём
    glm::vec2 wind{0.f};       ///< блоков в секунду
    Sky       sky      = Sky::Clear;
};

// ============================================================
// Размеры и сроки
// ============================================================
//
// Все числа здесь про ОДНО: «в своё время, но не слишком часто».
// Сутки в игре идут двадцать минут (DayCycle::DAY_LENGTH_SEC), и
// погода обязана жить на порядок медленнее, чем игрок успевает
// заметить, — иначе она мигает.

/// Как часто в одной ячейке может родиться циклон.
/// Полтора игровых дня — полчаса настоящего времени.
constexpr f64 CYCLONE_EPOCH_SEC = 1800.0;

/// Сколько циклон живёт. Три эпохи: в любой момент над миром идут
/// три поколения сразу, и новый застаёт старый живым.
constexpr f64 CYCLONE_LIFE_SEC = CYCLONE_EPOCH_SEC * 3.0;

/// Сторона ячейки сетки рождения, в блоках.
constexpr i32 CYCLONE_CELL = 6144;

/// Сколько ячеек в каждую сторону приходится опрашивать.
///
/// Считается из скорости и срока жизни: циклон за жизнь уезжает не
/// дальше CYCLONE_LIFE_SEC * DRIFT_MAX блоков, и ещё на полторы
/// радиуса достаёт его край. Меньше — и погода будет обрываться на
/// границе ячейки видимым швом.
constexpr i32 CYCLONE_CELL_SPAN = 3;

/// Сколько циклонов разом может накрыть одну точку.
constexpr u32 CYCLONE_MAX_NEAR = 12;

/// Поле погоды: чистая функция от зерна, места и времени.
///
/// Состояния нет намеренно. Погода, живущая в переменных, обязана
/// сохраняться вместе с миром, восстанавливаться при загрузке и
/// как-то догоняться после паузы. Погода, выведенная из времени
/// мира, не обязана ничего: мир уже помнит время, а время помнит
/// погоду. Сейв от этого не вырос ни на байт.
class WeatherField {
public:
    explicit WeatherField(u64 seed = 0) : seed_(seed) {}

    void setSeed(u64 s) { seed_ = s; }
    u64  seed() const   { return seed_; }

    /// Циклоны, чей край достаёт до точки. Возвращает сколько записал.
    u32 cyclonesNear(f64 timeSec, i32 wx, i32 wz,
                     Cyclone* out, u32 cap) const;

    /// Погода в точке.
    WeatherSample at(const TerrainGenerator& terrain,
                     i32 wx, i32 wz, f64 timeSec) const;

    /// Яркость радуги, 0..1.
    ///
    /// Радуга — не украшение по таймеру: она бывает, когда дождь
    /// ТОЛЬКО ЧТО кончился, солнце стоит низко и небо со стороны
    /// солнца уже расчистилось. Все три условия проверяются здесь, и
    /// прошлое спрашивается у той же чистой функции — временем
    /// назад.
    f32 rainbowAt(const TerrainGenerator& terrain,
                  i32 wx, i32 wz, f64 timeSec, f32 sunElevation) const;

    /// Идут ли осадки в этой точке снегом.
    ///
    /// Одно правило на всю игру, и то же число, по которому биом
    /// решает, тундра он или тайга: два правила разошлись бы, и
    /// снег пошёл бы над зелёной травой.
    static bool snowsAt(const TerrainGenerator& terrain, i32 wx, i32 wz);

private:
    u64 seed_ = 0;
};

/// Погода на экране: то же поле, но сглаженное во времени.
///
/// Поле честно отвечает про точку, а игрок ходит: шаг за угол
/// холма — и высота поверхности другая, и снег превращается в дождь
/// на одном шаге. Сглаживание убирает скачок, не трогая сам расчёт.
class Weather {
public:
    void init(u64 seed) { field_.setSeed(seed); reset(); }
    void reset();

    /// Догнать поле мгновенно — при входе в мир и после загрузки.
    void snap(const TerrainGenerator& terrain, const glm::vec3& pos, f64 timeSec);

    void update(const TerrainGenerator& terrain, const glm::vec3& pos,
                f64 timeSec, f32 sunElevation, f32 dt);

    /// ---- Сглаженное, для рендера и частиц ----
    f32       cloud()   const { return cloud_; }
    f32       precip()  const { return precip_; }
    f32       rainbow() const { return rainbow_; }
    f32       snowMix() const { return snowMix_; }   ///< 0 дождь, 1 снег
    glm::vec2 wind()    const { return wind_; }
    Sky       sky()     const { return sample_.sky; }
    const WeatherSample& sample() const { return sample_; }
    const WeatherField&  field()  const { return field_; }

    /// Насколько тучи гасят дневной свет, множитель 0.45..1.
    f32 lightScale() const;

private:
    void pull(const TerrainGenerator& terrain, const glm::vec3& pos,
              f64 timeSec, f32 sunElevation);

    WeatherField  field_;
    WeatherSample sample_{};
    f32 cloud_   = 0.f;
    f32 precip_  = 0.f;
    f32 rainbow_ = 0.f;
    f32 snowMix_ = 0.f;
    glm::vec2 wind_{0.f};

    /// Радуга и поле стоят недёшево, а меняются медленно: спрашивать
    /// их каждый кадр — значит платить шестьдесят раз в секунду за
    /// ответ, который не изменился.
    f32 pullTimer_ = 0.f;

    /// Куда тянется яркость радуги. Она гаснет и разгорается дольше
    /// всего остального: радуга, мигающая на границе условий, —
    /// худшее, что с ней можно сделать.
    f32 rainbowTarget_ = 0.f;
};

/// Как часто поле опрашивается заново, в секундах.
constexpr f32 WEATHER_PULL_SEC = 0.5f;

} // namespace world
