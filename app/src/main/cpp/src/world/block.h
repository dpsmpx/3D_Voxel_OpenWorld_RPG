/// Цвет грани в формате 0xRRGGBBAA.
///
/// Мир воксельный: у блока нет текстуры, у него есть материал. Цвет —
/// его единственное графическое свойство, остальное делают геометрия,
/// освещение и затенение углов.
///
/// Три цвета вместо одного — НЕ способ затенить грань. Затенением
/// занимается ровно одно место, таблица FACE_LIGHT в
/// shaders/voxel.frag, и оно применяется поверх любого из этих
/// цветов. Здесь разные цвета ставятся только там, где грани и правда
/// из разного материала: зелёная макушка на земляном боку у травы,
/// светлый спил на тёмной коре у дерева. У всего остального три поля
/// совпадают.
///
/// Раньше совпадали не все: у камня, песка, снега и руд верх был
/// светлее бока, а бок светлее низа. Наклон получался двойной — этот
/// плюс полусферный свет в шейдере, — и подправить его было нельзя,
/// не разбираясь каждый раз, какая из двух половин сейчас видна.
using BlockColor = u32;

constexpr BlockColor bcolor(u8 r, u8 g, u8 b, u8 a = 255) {
    return ((BlockColor)r << 24) | ((BlockColor)g << 16) |
           ((BlockColor)b << 8)  |  (BlockColor)a;
}

/// Свойства блока — компилируются один раз, читаются из рендера/физики
/// Как блок принимает падающее на него тело.
///
/// Всё — в БЛОКАХ ВЫСОТЫ ПАДЕНИЯ: «гасит падение с десяти блоков»
/// читается и сверяется глазами, квадрат скорости — нет. Высота и
/// квадрат скорости удара пропорциональны (v² = 2gh), поэтому высоты
/// можно просто вычитать: что погасила листва, того при ударе о
/// землю уже нет. В скорость переводит физика, по своей гравитации
/// (physics/impact.h).
///
/// Три свойства покрывают все материалы игры:
///   * мягкая опора (листва, снег, солома, песок) гасит часть
///     падения;
///   * проламывающаяся (та же листва, снег, солома, лёд, стекло)
///     уходит из-под тела, приняв слишком сильный удар, — и тело
///     летит дальше сквозь неё с тем, что осталось;
///   * жидкость (вода, лава) гасит нырок по глубине, а не разом.
struct BlockImpact {
    /// Падение с какой высоты опора гасит целиком. Сверх этого тело
    /// бьётся о неё с остатком. 0 — жёсткая опора.
    f32 absorb  = 0.f;
    /// С какой высоты падения опора проламывается и разрушается.
    /// 0 — не проламывается никогда.
    f32 giveWay = 0.f;
    /// Жидкость: во сколько раз быстрее падает скорость нырка с
    /// каждым блоком глубины — скорость убывает как e^(−drag·глубина).
    /// 0 — не жидкость.
    f32 drag    = 0.f;
};

struct BlockDef {
    const char* name;
    u8  isSolid       : 1;
    u8  isTransparent : 1;
    u8  isLiquid      : 1;
    u8  isEmissive    : 1;
    u8  emitsLight    : 1;
    u8  hasCollision  : 1;
    /// Размах крапчатости, 0..3. Ноль — цвет ровный.
    ///
    /// Крапчатость — небольшое отклонение яркости У КАЖДОГО БЛОКА,
    /// детерминированное по его координатам и зерну мира. Живая земля
    /// не бывает однотонной: поле, крона и пашня складываются из
    /// оттенков, и без них большая поверхность одного материала
    /// читается заливкой, а не множеством кубов.
    ///
    /// Свойство материала, а не места: камень, песок, доска и снег
    /// обязаны оставаться ровными. Крапчатость получает только то,
    /// что в природе разнородно, — трава, листва, земля.
    ///
    /// Считает отклонение фрагментный шейдер (shaders/voxel.frag);
    /// сюда, в вершину, едет ТОЛЬКО номер класса. Причина в жадном
    /// слиянии: положи мешер готовый цвет в вершину — и квады с
    /// разным оттенком перестали бы склеиваться, то есть поле из
    /// одного слитого квада распалось бы на тысячу отдельных.
    u8  colorJitter   : 2;
    u8  lightLevel;      // 0..15 если emissive
    /// Мешер блок не рисует: его рисует кто-то другой. Ствол дерева
    /// из мелких вокселей (world/flora_types.h) стоит в сетке мира
    /// невидимыми блоками — для столкновений, пути, рубки и огня, — а
    /// видна модель. Такой блок обязан быть и прозрачным: грани
    /// соседей к нему выводятся, тени он не бросает.
    u8  isInvisible = 0;
    BlockColor colorTop;
    BlockColor colorSide;
    BlockColor colorBottom;
    f32 hardness;        // время добычи в секундах
    u32 toolFlags;       // какие инструменты эффективны
    /// Как принимает падение. См. BlockImpact.
    BlockImpact impact{};

    /// Цвет грани по её индексу: 0..5 это +X, -X, +Y, -Y, +Z, -Z.
    BlockColor faceColor(u8 face) const {
        return face == 2 ? colorTop : (face == 3 ? colorBottom : colorSide);
    }
};

/// Шаг размаха крапчатости: класс 1 — ±2 % цвета, класс 3 — ±6 %.
///
/// Ровно это же число стоит в shaders/voxel.frag, и разойтись им
/// нельзя: там оно превращает номер класса в отклонение. Сверяет их
/// проверка — текстом, как и блок CameraUbo.
constexpr f32 COLOR_JITTER_STEP = 0.020f;

/// Максимальный размах: класс 3.
constexpr f32 COLOR_JITTER_MAX = COLOR_JITTER_STEP * 3.f;

/// Реестр блоков — заполняется на старте
class BlockRegistry {
public:
    static constexpr u16 MAX_BLOCKS = 1024;

    void registerBlock(u16 id, const BlockDef& def);
    const BlockDef& get(u16 id) const;
    /// Задать, как блок принимает падение. Отдельно от
    /// registerBlock: у той и так двенадцать позиционных полей, а
    /// мягких блоков — горстка.
    void setImpact(u16 id, const BlockImpact& impact);

    bool isSolid(u16 id)       const { return get(id).isSolid; }
    bool isTransparent(u16 id) const { return get(id).isTransparent; }
    bool isOpaque(u16 id)      const { return !get(id).isTransparent; }

private:
    std::array<BlockDef, MAX_BLOCKS> defs_{};
    u16 maxId_ = 0;
};

/// Глобальные ID — согласованы с реестром
enum BlockId : u16 {
    AIR     = 0,
    STONE   = 1,
    DIRT    = 2,
    GRASS   = 3,
    SAND    = 4,
    WATER   = 5,
    WOOD    = 6,
    LEAVES  = 7,
    SNOW    = 8,
    ICE     = 9,
    LAVA    = 10,
    IRON_ORE= 11,
    GOLD_ORE= 12,
    BEDROCK = 13,

    // Строительные материалы. Деревню из одного WOOD и LEAVES
    // построить нельзя: стены, крыша и пол выходят одного цвета, и
    // дом читается как куб с кустом сверху. Ровно так он и читался.
    PLANK   = 14,   ///< тёсаная доска — стены
    THATCH  = 15,   ///< солома — кровля
    GLASS   = 16,   ///< окно; прозрачное, но твёрдое
    LANTERN = 17,   ///< фонарь; светит вместо лужи лавы в доме

    /// Кактус. Ствол пустынного «дерева» — до сих пор он строился из
    /// WOOD с пометкой «временно; в идеале — CACTUS», и посреди
    /// песков стояли деревянные столбики цвета дубовой коры.
    CACTUS  = 18,

    /// Тёсаный камень — кладка.
    ///
    /// Отдельно от STONE, и не ради красоты: стена из STONE
    /// неотличима от скалы, в которую она упирается. Ни глазу, ни
    /// проверке: «стены дома» пришлось бы искать среди полумиллиона
    /// блоков коренной породы в том же радиусе. Каменная деревня без
    /// своего материала вообще не читается как деревня.
    BRICK   = 19,

    /// Факел. Единственный светильник, который игрок носит с собой и
    /// ставит куда хочет.
    ///
    /// Фонарь есть давно, но он твёрдый, дорогой и стоит в домах —
    /// пещеру им не осветить. Факел сквозной: сквозь него ходят, он
    /// не мешает ни движению, ни поиску пути, и ставится он там, где
    /// темно.
    TORCH   = 20,

    /// Щебень: осыпи под скалами, галечные отмели, дно глубокого моря.
    /// Даёт камень — щебень и есть битый камень.
    GRAVEL  = 21,
    /// Выгоревшая трава: саванна и степь. Та же трава, другой сезон —
    /// и выкопанная, она обычная трава.
    DRY_GRASS = 22,
    /// Ствол дерева: невидимый блок в сетке мира, модель рисует рендер
    /// растений. Рубится как дерево и даёт древесину; срубленный,
    /// роняет весь ствол.
    TRUNK   = 23,
    /// То же для кактуса.
    CACTUS_CORE = 24,

    /// Количество заданных ID. Служит верхней границей для таблиц,
    /// индексируемых блоком (атлас текстур, block→item).
    BLOCK_COUNT
};

/// «Неизвестно»: соседний чанк ещё не загружен.
///
/// Это НЕ блок и НЕ воздух. Раньше отсутствующий сосед отдавался как
/// AIR, и мешер честно строил по такой границе наружную грань — стену
/// во всю толщу земли. Пока сосед не подгрузится, она так и стоит
/// перед камерой чёрным клином: у грани, смотрящей внутрь массива,
/// открытость неба нулевая.
///
/// Значение вне диапазона реестра намеренно: любое обращение
/// blocks().get(UNKNOWN) — ошибка, и её видно сразу.
constexpr u16 UNKNOWN = 0xFFFF;

/// Можно ли решать по этому соседу, строить грань или нет.
inline bool neighborKnown(u16 id) { return id != UNKNOWN; }

/// Рисуется ли материал со смешиванием, то есть видно ли сквозь него.
/// Смотрим на альфу цвета, а не на флаг isTransparent: листва и лава
/// помечены прозрачными, чтобы мешер не склеивал их грани, но рисуются
/// они непрозрачными. Сквозь видно только воду и лёд.
inline bool isSeeThrough(const BlockDef& d) {
    return (d.colorTop    & 0xFFu) < 255u
        || (d.colorSide   & 0xFFu) < 255u
        || (d.colorBottom & 0xFFu) < 255u;
}

