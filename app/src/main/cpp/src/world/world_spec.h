/**
 * @file world_spec.h
 * @brief Мир: чем один мир отличается от другого — имя и зерно.
 */
#pragma once
#include "../core/types.h"

namespace world {

/// Зерно нового мира — каждый раз другое.
///
/// Прежде зерно было константой: все игроки всех запусков ходили по
/// одному и тому же рельефу, и «новый мир» означал ровно то же
/// побережье. Случайность берётся у системы, а не у счётчика кадров:
/// два запуска подряд обязаны разойтись.
u64 randomWorldSeed();

/// Длина имени мира вместе с завершающим нулём.
///
/// Ровно столько же, сколько в save::SlotMeta::worldName: имя,
/// которое не сохранится целиком, незачем и набирать.
constexpr u32 WORLD_NAME_CAP = 32;

/// Зерно по тому, что набрал игрок.
///
/// Число — значит число: игрок, вводящий 12345, ждёт тот самый мир,
/// который ему назвали, а не хэш от строки «12345». Всё остальное
/// хэшируется, потому что «Долина» должна давать мир, а не отказ.
/// Пустая строка — ноль; звать за случайным зерном — дело
/// вызывающего, здесь про это знать неоткуда.
u64 seedFromText(const char* text);

/// Имя по умолчанию для мира с этим зерном.
///
/// Мир без имени в списке неразличим: девять строк «—» не помогают
/// выбрать. out — не меньше WORLD_NAME_CAP байт.
void defaultWorldName(char* out, u32 cap, u64 seed);

} // namespace world
