/**
 * @file landform.h
 * @brief Мир: крупные формы рельефа — из чего складывается высота.
 *
 * Высота колонки раньше была суммой шумов: континент, «эрозия»,
 * пики, узкая полоса хребта и мелкая рябь. Каждый шум сам по себе
 * гладкий, и в сумме выходила ровная холмистая скатерть с редкими
 * лентами гор — ни плато, ни долин, ни горной страны.
 *
 * Здесь высота строится иерархией масштабов:
 *
 *   macro — регион: суша или море, горная страна, нагорье, низина.
 *           Поля с длиной волны в километры, у каждого своя роль.
 *   meso  — формы внутри региона: отроги и распадки хребта, холмы,
 *           край плато, уступы, ложбины. Какие формы и какой силы —
 *           решает регион, а не общий для всех шум.
 *   micro — лёгкая неровность, чтобы склон не был ступенчатой
 *           лестницей по линейке.
 *
 * Горы — не купола, а цепи: маска горной страны вытянута вдоль
 * своего направления (у каждой области оно своё), а внутри неё рельеф
 * — гребневой мультифрактал, у которого тонкие детали растут на
 * гребнях и гаснут в распадках. Это дешёвое подобие эрозии: хребты
 * острые, долины между ними сглажены, как будто их вымыла вода.
 *
 * Округление до блоков — последний шаг, в TerrainGenerator::column.
 * Всё здесь — непрерывные функции мировых координат: чанк не знает
 * соседей, и швов быть не может.
 */
#pragma once
#include "../core/types.h"
#include "noise.h"

namespace world {

/// Характер местности. Не отдельная сущность мира, а ответ на
/// вопрос «какая здесь форма рельефа»: для биомов, растительности,
/// отладочной карты и будущих построек (дороги, поселения).
enum class Landform : u8 {
    Ocean = 0,
    Coast,      ///< полоса у моря
    Lowland,    ///< низина: сырая, плоская
    Plains,     ///< равнина
    Hills,      ///< холмы
    Plateau,    ///< плато: ровный верх, обрывистый край
    Foothills,  ///< предгорья
    Mountains,  ///< горная страна
    Peaks,      ///< высокогорье
    Count
};

const char* landformName(Landform f);
/// Цвет слоя «landform» отладочной карты, 0xRRGGBB.
u32 landformDebugColor(Landform f);

/// Направление хребтов области — через три НЕПОДВИЖНЫЕ оси.
///
/// Поворачивать мировые координаты на плавно меняющийся угол нельзя:
/// сдвиг угла на сотую доли радиана на расстоянии в сто тысяч блоков
/// от начала мира сдвигает точку выборки на тысячу блоков, и узор
/// сжимается гармошкой тем сильнее, чем дальше от начала. Вместо
/// этого вытянутый шум считается в трёх осях, повёрнутых на 0°, 60°
/// и 120°, — каждая сама по себе обычный неискажённый шум, — и
/// смешивается по весам от угла области. Работают не больше двух
/// осей сразу.
struct OrientFrames {
    static constexpr f32 COS[3] = { 1.f, 0.5f, -0.5f };
    static constexpr f32 SIN[3] = { 0.f, 0.8660254f, 0.8660254f };
    f32 w[3] = { 1.f, 0.f, 0.f };   ///< в сумме единица
    f32 norm = 1.f;                 ///< 1 / sqrt(сумма квадратов весов)

    static OrientFrames of(f32 angle);
};

/// Крупные поля одной колонки: считаются в BiomeField::fields вместе
/// с климатом (они того же масштаба) и приходят сюда готовыми.
struct MacroFields {
    f32 continent = 0.f;   ///< -1..1, море → суша
    f32 humidity  = 0.f;   ///< -1..1
    f32 erosion   = 0.5f;  ///< 0..1: 0 — изрезано, 1 — сглажено
    f32 peaks     = 0.f;   ///< 0..1: насколько высок этот участок гор
    f32 mountain  = 0.f;   ///< 0..1: маска горной страны
    f32 hills     = 0.f;   ///< 0..1: маска холмов
    f32 plateau   = 0.f;   ///< 0..1: маска плато (край — обрыв)
    f32 basin     = 0.f;   ///< 0..1: маска низины
    f32 region    = 0.5f;  ///< 0..1: характер области
    f32 orient    = 0.f;   ///< направление хребтов области, радианы
};

/// Результат: высота до округления и то, из чего она сложилась.
struct LandformSample {
    f32      height = 0.f;
    /// Высота без холмов и мелочи — по ней гидросеть решает, куда
    /// течёт вода. Холмы здесь — волны в сотню блоков, и каждая ямка
    /// между ними на грубой сетке стока становилась озером: реки шли
    /// цепочками прудов. Вода течёт по крупному рельефу, а холмы
    /// река прорезает долиной — сначала сток, потом долина.
    f32      route = 0.f;
    f32      ridge  = 0.f;   ///< 0..1: близость к гребню (для скал)
    Landform form   = Landform::Plains;
};

/// Шумы средних и мелких масштабов. Своё зерно у каждого; живёт в
/// TerrainGenerator, все методы — чистые функции координат.
class LandformNoise {
public:
    explicit LandformNoise(u64 seed);

    LandformSample sample(const MacroFields& m, i32 x, i32 z) const;

    /// Гребневой мультифрактал (Масгрейв): 0..~1. На гребнях детали
    /// набирают вес, в распадках гаснут — отсюда «вымытый» вид.
    f32 ridgedMultifractal(f32 x, f32 z, u32 octaves) const;

private:
    SimplexNoise mountain_;
    SimplexNoise warp_;
    SimplexNoise hills_;
    SimplexNoise plateau_;
    SimplexNoise detail_;
};

} // namespace world
