#pragma once
#include "../core/types.h"
#include "chunk_manager.h"
#include <glm/glm.hpp>
#include <vector>

namespace world {

/// Один осколок.
///
/// Это маленький КУБ, а не точка и не спрайт: игра воксельная, и
/// всё, что от неё откалывается, обязано быть из того же материала,
/// что и она сама.
struct Particle {
    glm::vec3 pos{0.f};
    glm::vec3 vel{0.f};
    /// Ребро куба в блоках.
    f32 size = 0.f;
    /// Остаток жизни, сек.
    f32 life = 0.f;
    /// Полный срок — по нему считается затухание.
    f32 lifeTime = 0.f;
    /// Своя гравитация: пыль из-под ног оседает медленнее, чем
    /// отлетает щепка от разбитого камня.
    f32 gravity = 0.f;
    /// Высота опоры под осколком.
    ///
    /// Считается ОДИН раз, сканированием колонки вниз, — ровно как
    /// `Drop::killY` у осадков и ровно по той же причине: честная
    /// проверка столкновения каждый кадр стоила бы тысяч чтений
    /// вокселя ради ответа, который не меняется.
    ///
    /// -inf означает «опоры под ним не нашлось»: такой осколок
    /// падает, пока не кончится его срок.
    f32 restY = 0.f;
    /// Фаза кувыркания. Куб, летящий гранями по осям мира, читается
    /// как блок, забытый в воздухе, а не как осколок.
    f32 spin = 0.f;
    f32 spinRate = 0.f;
    u32 color = 0;              ///< RGBA, как BlockColor
    bool probed  = false;       ///< опора под ним уже найдена
    bool resting = false;       ///< лежит на опоре и догорает
    bool alive   = false;
};

/// Описание горсти осколков.
///
/// Один тип на все поводы: разница между щепками от блока и брызгами
/// от удара — это ЧИСЛА, а не код. Заводить под каждый повод свой
/// излучатель значило бы писать одно и то же пять раз.
struct Burst {
    glm::vec3 origin{0.f};
    /// Преимущественное направление разлёта.
    glm::vec3 dir{0.f, 1.f, 0.f};
    u32 count = 8;
    f32 speed = 4.f;
    /// 0 — все строго вдоль `dir`, 1 — равномерно во все стороны.
    f32 spread = 0.5f;
    f32 size = 0.09f;
    f32 life = 0.6f;
    f32 gravity = 18.f;
    u32 color = 0xFFFFFFFFu;
    /// Второй цвет; 0 — брать только первый.
    ///
    /// Верх и бок блока, шкура и глаза твари: горсть из двух оттенков
    /// читается как материал, а из одного — как заливка.
    u32 color2 = 0;
};

/// Пул воксельных частиц.
///
/// Без ECS намеренно. Сущность на каждый осколок — это запись в
/// каждом пуле компонентов, разрушение через общий список и
/// перебор реестра ради полусекундной пылинки; при сотне осколков в
/// кадр это заметно дороже самих частиц. Здесь — один непрерывный
/// массив, который обходится подряд.
class Particles {
public:
    /// Потолок числа живых осколков.
    ///
    /// Пятьсот кубов — это те же пятьсот инстансов в уже
    /// существующем вызове отрисовки и 24 КБ на кадр. Больше на
    /// телефоне не нужно: горсть от одного удара — это десяток.
    static constexpr u32 MAX = 512;

    /// Дальше этого расстояния от глаз осколки гасятся.
    ///
    /// Драка за спиной игрока не обязана занимать пул: то, чего не
    /// видно, не обратная связь.
    static constexpr f32 CULL_RADIUS = 56.f;

    /// На сколько блоков вниз ищется опора.
    static constexpr i32 GROUND_PROBE = 10;

    /// Сколько колонок разрешено просканировать за кадр.
    static constexpr u32 PROBE_BUDGET = 192;

    /// Сколько осколок лежит на земле, прежде чем растаять.
    static constexpr f32 REST_LIFE = 0.55f;

    /// Сопротивление воздуха, 1/с. Без него горсть разлетается по
    /// прямым и выглядит салютом, а не обломками.
    static constexpr f32 DRAG = 2.2f;

    void reset();

    /// Выпустить горсть. Мир при этом не нужен: опору под осколками
    /// найдёт ближайший update().
    ///
    /// Так сделано затем, чтобы звать эту функцию можно было оттуда,
    /// где мира нет, — из расчёта урона, например.
    void emit(const Burst& b);

    void update(ChunkManager& world, const glm::vec3& eye, f32 dt);

    const std::vector<Particle>& items() const { return pool_; }

    /// Сколько осколков живо. Считается и при рождении, и при
    /// обновлении: горсть, выпущенная после update этого кадра, тоже
    /// должна быть посчитана — иначе рендер недооценит список ровно
    /// в тот кадр, когда игрок ударил.
    u32 liveCount() const { return live_; }

private:
    /// Найти свободное место. Пул кольцевой: когда он полон,
    /// затирается самое старое. Свежая обратная связь важнее
    /// доживающей.
    Particle& allocate();

    f32 frand();

    std::vector<Particle> pool_;
    u32 cursor_ = 0;
    u32 live_ = 0;
    u32 rng_ = 0x2545F491u;
};

/// Общий пул частиц.
///
/// Ровно по той же причине, по которой глобален `audio::events()`:
/// повод для осколков возникает в глубине расчёта — в применении
/// урона, в сломе блока, в приземлении, — и протаскивать туда ссылку
/// пришлось бы через десяток сигнатур, ни одна из которых о частицах
/// знать не должна.
///
/// Замка у пула нет и не нужно: все поводы — урон, слом, приземление
/// — считаются в главном потоке, а рабочие потоки заняты генерацией
/// и мешированием чанков и о бое не знают вовсе.
Particles& particles();

// ------------------------------------------------------------
// Поводы
//
// Здесь, а не на местах вызова: цвет осколка обязан браться из
// настоящего блока и настоящей оснастки, и правило это должно быть
// записано ОДИН раз.
// ------------------------------------------------------------

/// Блок разбит: щепки его собственного цвета.
void blockBreakBurst(const glm::ivec3& block, u16 blockId);

/// Приземление: пыль из-под ног, цветом опоры.
/// `fallSpeed` — модуль скорости удара о землю, блоков/с.
void landingBurst(const glm::vec3& feet, u16 groundBlock, f32 fallSpeed);

/// Попадание по существу: брызги его цвета, прочь от бьющего.
/// `severity` — доля здоровья, снятая ударом, 0..1.
void woundBurst(const glm::vec3& at, const glm::vec3& away,
                u32 bodyColor, f32 severity, bool critical);

/// Существо погибло: оно рассыпается собственным цветом.
void deathBurst(const glm::vec3& at, u32 bodyColor);

} // namespace world
