/**
 * @file village_deeds.h
 * @brief Мир: следы того, что игрок сделал для деревни.
 */
#pragma once
#include "../core/types.h"
#include "features.h"

namespace world {

class ChunkManager;

/// Сколько факелов может зажечься в одной деревне.
///
/// Восемь — это кольцо вокруг колодца с шагом в сорок пять
/// градусов. Больше не нужно: деревня и так становится видна
/// ночью издалека, а превращать её в костёр незачем.
constexpr u32 VILLAGE_DEED_SPOTS = 8;

/// Радиус кольца факелов вокруг колодца, в блоках.
constexpr i32 VILLAGE_DEED_RADIUS = 4;

/// Место i-го факела: точка кольца вокруг колодца.
///
/// Высота НЕ считается: её знает только мир, и берёт её
/// lightVillageDeed. Здесь — столбец, в котором факел должен встать.
glm::ivec3 villageDeedSpot(const VillageSite& site, u32 index);

/// Сколько следов уже оставлено — сколько факелов горит.
///
/// Считается ПО МИРУ, а не по отдельной таблице. Таблица была бы
/// вторым местом, где живёт одно и то же, и разойтись с миром она
/// могла бы молча: сохранение мира везёт изменённые блоки, и факелы
/// в нём уже есть. Спрашивать надо у того, кто помнит.
u32 villageDeeds(ChunkManager& world, const VillageSite& site);

/// Зажечь ещё один факел за сделанное для деревни.
///
/// @return false, если все места заняты или ставить некуда
bool lightVillageDeed(ChunkManager& world, const VillageSite& site);

/// Деревня, которой принадлежит точка (например, раздатчик заданий).
///
/// Ищется в своём супер-чанке и в восьми соседних: колодец стоит в
/// середине деревни, а житель может оказаться и за границей
/// супер-чанка. Не нашлась — `exists == false`.
VillageSite villageAtPoint(ChunkManager& world, const glm::ivec3& p);

} // namespace world
