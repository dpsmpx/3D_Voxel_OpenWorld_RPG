/**
 * @file spawn.h
 * @brief Мир: выбор точки, в которой игрок появляется впервые.
 */
#pragma once
#include "../core/types.h"
#include "terrain.h"
#include <glm/glm.hpp>

namespace world {

/// Почему точка не подошла.
///
/// Перечисление, а не булево: «не годится» ничего не объясняет, а
/// разбираться, отчего в целом мире не нашлось места, приходится
/// именно по причинам.
enum class SpawnReject : u8 {
    Ok = 0,
    UnderWater,   ///< стоять пришлось бы в воде
    Steep,        ///< обрыв: соседние колонки слишком разной высоты
    BadBiome,     ///< океан, вулкан, Чёрный лес
    Cave,         ///< под ногами пещера — провалится
    Structure,    ///< на этой земле уже стоит постройка
    Sinkhole,     ///< провал: появиться в нём значит очнуться в падении
    Lair,         ///< логово: появиться в стае значит сразу умереть
    Count
};

/// Название причины — для журнала и для теста.
const char* spawnRejectName(SpawnReject r);

/// Годится ли точка, чтобы в ней появиться.
///
/// outY — уровень, на котором встанут ноги (тот самый первый
/// воздушный блок над землёй, который возвращает surfaceHeight).
/// Заполняется и при отказе: по нему видно, ГДЕ именно не годится.
SpawnReject spawnPointCheck(const TerrainGenerator& terrain, u64 worldSeed,
                            i32 wx, i32 wz, i32& outY);

/// Итог перебора.
struct SpawnSearch {
    bool       found = false;
    glm::ivec3 point{0};
    /// Сколько точек просмотрено и сколько отвергнуто по каждой
    /// причине. Нужно не для игры, а чтобы понять, отчего поиск
    /// провалился: «нигде не нашлось» без разбивки — это тупик.
    i32 tried = 0;
    i32 rejected[(u32)SpawnReject::Count] = {};
};

/// Шаг перебора в блоках.
///
/// Четыре, а не один: соседние блоки почти всегда одинаковы, и
/// перебор с шагом в блок тратит в шестнадцать раз больше запросов
/// к рельефу ради того же ответа.
constexpr i32 SPAWN_STEP = 4;

/// Половина стороны области перебора.
///
/// Пятьдесят: область сто на сто блоков, как и задумано. Этого
/// хватает — в ней 625 точек с шагом в четыре.
constexpr i32 SPAWN_HALF_EXTENT = 50;

/// Перебрать область вокруг центра и вернуть ПЕРВУЮ годную точку.
///
/// Обход идёт кольцами от середины наружу, а не строками: ближняя к
/// центру годная точка находится раньше дальней, и игрок появляется
/// там, куда целились, а не в углу области.
SpawnSearch findSpawn(const TerrainGenerator& terrain, u64 worldSeed,
                      i32 centerX, i32 centerZ,
                      i32 halfExtent = SPAWN_HALF_EXTENT);

/// Точка появления с запасным вариантом.
///
/// Если в области не нашлось ничего (мир из одного океана — такое
/// бывает), игрок всё равно должен куда-то встать: ставим его на
/// уровень моря в середине области. Утонуть он там не утонет —
/// поплывёт.
glm::vec3 spawnPositionOrFallback(const TerrainGenerator& terrain,
                                  u64 worldSeed, i32 centerX, i32 centerZ);

} // namespace world
