/// Контекст генерации — то, что доступно любой фиче.
/// Содержит ссылку на terrain и seed мира.
struct FeatureContext {
    const TerrainGenerator* terrain;
    u64 seed;

    /// Готовые колонки чанка, CHUNK_SIZE x CHUNK_SIZE, индекс
    /// x * CHUNK_SIZE + z. Заполняется один раз при генерации:
    /// без неё каждая фича пересчитывала высоту и климат заново,
    /// и один чанк стоил четырёх полных проходов по шуму.
    /// nullptr допустим — тогда данные считаются на лету.
    const TerrainGenerator::Column* columns = nullptr;

    /// Колонка по локальным координатам чанка.
    TerrainGenerator::Column columnAt(i32 lx, i32 lz, i32 wx, i32 wz) const {
        if (columns && (u32)lx < (u32)CHUNK_SIZE && (u32)lz < (u32)CHUNK_SIZE)
            return columns[lx * CHUNK_SIZE + lz];
        return terrain->column(wx, wz);
    }
};

/// Заполняет чанк целиком: слои рельефа по готовым колонкам, затем
/// все фичи в правильном порядке. Одно место на весь проект — и
/// потоковая генерация мира, и офлайн-рендер из tools/preview
/// получают один и тот же ландшафт. Раньше раскладка слоёв была
/// выписана в обоих, и офлайн-рендер мог незаметно разойтись с игрой
/// ровно тогда, когда он нужнее всего.
///
/// Замок на вокселях не берётся: вызывающий знает, нужен ли он.
/// columns — CHUNK_SIZE x CHUNK_SIZE, индекс x * CHUNK_SIZE + z.
void generateChunkVoxels(Chunk& chunk, const TerrainGenerator& terrain,
                         const TerrainGenerator::Column* columns, u64 seed);

/// Считает колонки чанка в переданный буфер (он будет нужного размера).
void computeChunkColumns(const TerrainGenerator& terrain, i32 chunkX, i32 chunkZ,
                         std::vector<TerrainGenerator::Column>& out);

// ============================================================
// Features применяются к чанку ПОСЛЕ terrain-слоёв, но ДО
// построения меша. Каждая фича пишет в voxels[] по локальным
// координатам.
//
// Система рассчитана на детерминированность: один и тот же
// (seed, chunk) всегда даёт один результат.
// ============================================================

/// --- Деревья: анкерные позиции в чанке, canopy может пересекать границу ---
void applyTrees(Chunk& chunk, const FeatureContext& ctx);

/// --- Пещеры: карвинг после слоёв, до руд ---
void applyCaves(Chunk& chunk, const FeatureContext& ctx);

/// --- Руды: жилы после карвинга ---
void applyOres(Chunk& chunk, const FeatureContext& ctx);

/// --- Вода/лава: заполнение уровней ---
void applyLiquids(Chunk& chunk, const FeatureContext& ctx);

/// --- Структуры: деревни, подземелья, руины, алтари ---
/// Работают через super-chunk grid: 8×8 чанков = 256×256 блоков.
/// Структура ставится детерминированно по (superX, superZ).
/// При генерации чанка проверяются все super-чанки в радиусе 2 —
/// структура может пересекать границы.
void applyStructures(Chunk& chunk, const FeatureContext& ctx);

/// --- Дороги: от деревни к соседней деревне ---
/// Кладутся после структур и до деревьев: мостовая деревни должна
/// остаться сверху, а лес — не прорасти сквозь дорогу.
void applyRoads(Chunk& chunk, const FeatureContext& ctx);

/// Запрос структур мира.
///
/// Структуры размещаются детерминированно по super-chunk-сетке
/// 8x8 чанков. Снаружи это нужно, чтобы спавнить боссов и NPC
/// там, где генератор поставил подземелье или деревню, — не
/// перебирая воксели.
struct DungeonSite {
    bool       exists = false;
    glm::ivec3 center{0};   ///< центр зала босса в мировых координатах
    u32        seed = 0;
};

/// Подземелье в супер-чанке (sx, sz), если оно там сгенерировано.
DungeonSite dungeonAt(i32 superX, i32 superZ, u64 worldSeed);

/// Подземелье внутри исполинского дерева.
///
/// Отдельно от dungeonAt: у того зал лежит под землёй на заранее
/// известной глубине, а здесь высота зала считается от рельефа, и без
/// генератора её не узнать.
///
/// @return центр — верхний зал, где и стоит босс
DungeonSite treeDungeonAt(i32 superX, i32 superZ, u64 worldSeed,
                          const TerrainGenerator* terrain);

/// Деревня в супер-чанке (sx, sz), если она там сгенерирована.
///
/// Раскладку деревни спрашивают снаружи: спавнеру NPC надо знать, где
/// колодец, чтобы расставить вокруг него жителей. Он эту раскладку
/// ВЫЧИСЛЯЛ САМ, повторяя и хэш, и порог, и смещение — с комментарием
/// «совпадает с features::structs::layoutFor». Две копии одного
/// правила расходятся молча: порог сдвинут в одном месте, и жители
/// остаются стоять в чистом поле, где деревни больше нет.
/// Уклад деревни.
///
/// Деревни были одинаковы до блока: один и тот же круг домов из
/// доски под соломой, один и тот же набор жителей. Уклад меняет и
/// облик, и состав — так, чтобы разницу было видно с порога, а не
/// по выпадающему списку.
enum class VillageStyle : u8 {
    Farmstead = 0,  ///< хлебная: доска и солома, просторно, много жителей
    Stonemason,     ///< каменная: камень и доска, тесно, много ремесла
    Garrison,       ///< сторожевая: камень, кольцо плотное, вдвое стражи
    Woodland,       ///< лесная: бревно и солома, дома вразброс
    Count
};

/// Название уклада — для журнала и для рассказа о деревне.
const char* villageStyleName(VillageStyle s);

struct VillageSite {
    bool       exists = false;
    glm::ivec3 center{0};   ///< колодец в центре деревни
    u32        seed = 0;
    /// Уклад. Считается из того же seed, что и всё остальное в
    /// деревне: спрашивающий снаружи (спавнер NPC) и генератор
    /// обязаны сойтись во мнении, какая это деревня.
    VillageStyle style = VillageStyle::Farmstead;
};

/// Из чего сложены дома этого уклада.
///
/// Спрашивают снаружи: «дом построен, а не насыпан» проверяется по
/// материалу стены и кровли, и зашивать в проверку доску с соломой
/// значило бы проверять один уклад из четырёх.
struct VillageMaterials {
    u16 wall;   ///< поле стены
    u16 post;   ///< угловая стойка
    u16 roof;   ///< кровля
};
VillageMaterials villageMaterialsOf(VillageStyle s);

/// Уклад по зерну деревни. Одна функция на всех, кто спрашивает.
VillageStyle villageStyleOf(u32 villageSeed);

/// `terrain` — если передан, деревня ещё и проверяется на сушу.
///
/// Размещение структур смотрит ТОЛЬКО на хэш и про рельеф не знает
/// ничего, поэтому деревни исправно вырастали в океане: дома по
/// колено в воде, дорожки на дне, жители посреди моря. Проверка одна
/// и живёт здесь — иначе спавнер NPC и генератор разойдутся во
/// мнении, где деревня есть.
VillageSite villageAt(i32 superX, i32 superZ, u64 worldSeed,
                      const TerrainGenerator* terrain = nullptr);

/// Размер супер-чанка в блоках — шаг сетки структур.
constexpr i32 SUPER_CHUNK_BLOCKS = 8 * CHUNK_SIZE;

/// --- Логова: области, где водится один-единственный вид ---
///
/// Мир, где всякий моб берётся из таблицы биома, ровный: волк и
/// скелет встречаются везде поровну, и идти куда-то за кем-то
/// конкретным незачем. Логово — область, в которой таблица биома не
/// действует: там водится ровно ОДИН вид, водится он и днём, и
/// водится гуще обычного.
///
/// Логово кладётся на ту же сетку супер-чанков, что и структуры, и
/// считается из того же хэша. Блоков оно не ставит: это правило
/// спавна, а не постройка, и генератор чанка про него не знает
/// ничего.
enum class LairKind : u8 {
    None = 0,
    Wolves,     ///< волчье логово
    Skeletons,  ///< костяное поле
    Goblins,    ///< гоблинская стоянка
    Slimes,     ///< слизневая топь
};

struct LairSite {
    bool       exists = false;
    glm::ivec3 center{0};
    f32        radius = 0.f;
    LairKind   kind   = LairKind::None;
};

/// Логово в супер-чанке (sx, sz), если оно там есть.
///
/// Логово занимает только ПУСТЫЕ ячейки сетки: где стоит деревня,
/// подземелье, руины или алтарь, логова не будет. Иначе стая волков
/// поселилась бы на деревенской площади, и деревня перестала бы быть
/// местом, куда возвращаются.
///
/// `terrain` обязателен: логово в океане — это логово, в котором
/// некому стоять.
LairSite lairAt(i32 superX, i32 superZ, u64 worldSeed,
                const TerrainGenerator* terrain);

/// --- Болотные бочаги ---
///
/// Болото было болотом только по имени: та же трава, тот же рельеф,
/// разве что суше на два блока и деревья сухие. Стоячая вода — то
/// единственное, по чему болото узнают.
void applySwampPools(Chunk& chunk, const FeatureContext& ctx);

/// --- Тайники: сокровище под старыми руинами ---
///
/// Сокровище тайное в буквальном смысле: замурованная камера под
/// развалинами, куда нет ни хода, ни лестницы. Добираются до неё
/// СВЕРХУ, разобрав землю, — и знать, где копать, можно только от
/// того, кто помнит эти развалины.
///
/// Потому клад и привязан к руинам, а не рассыпан по карте: клад в
/// чистом поле не находят, его находят по рассказу.
struct TreasureSite {
    bool       exists = false;
    glm::ivec3 center{0};   ///< середина камеры
    u32        seed = 0;
};

/// Тайник в супер-чанке (sx, sz), если он там есть.
TreasureSite treasureAt(i32 superX, i32 superZ, u64 worldSeed,
                        const TerrainGenerator* terrain);

/// Ближайший тайник к точке, не дальше maxBlocks. Спрашивают квесты:
/// подсказка ведёт к настоящему кладу, а не к случайной точке.
TreasureSite nearestTreasure(const glm::ivec3& from, u64 worldSeed,
                             const TerrainGenerator* terrain,
                             i32 maxBlocks);

/// --- Провалы: обрывы, в которые падают ---
///
/// Дыра в земле от поверхности до самых пещер. Не пещера и не
/// каньон: у провала отвесные стены и нет пологого спуска — внутрь
/// попадают падая, а не заходя.
///
/// Каменный венец по краю не украшение: без него дыра в траве
/// читается как ошибка генератора, а не как место, куда можно
/// упасть.
struct SinkholeSite {
    bool       exists = false;
    glm::ivec3 center{0};   ///< середина устья, на уровне земли
    i32        radius = 0;
    i32        bottom = 0;  ///< дно
};

/// Провал в супер-чанке (sx, sz), если он там есть.
SinkholeSite sinkholeAt(i32 superX, i32 superZ, u64 worldSeed,
                        const TerrainGenerator* terrain);

/// --- Замки: то, что стоит в Чёрном лесу ---
///
/// Огромная постройка, а не домик: стена в семьдесят блоков по
/// стороне, четыре угловые башни и донжон посередине. Ставится
/// только в Чёрном лесу и только в пустой ячейке сетки — рядом с
/// деревней замок читался бы как её часть, а он ничей.
struct CastleSite {
    bool       exists = false;
    glm::ivec3 center{0};   ///< середина донжона, на уровне двора
};

/// Полширины замка: от середины донжона до внешнего края стены.
///
/// Живёт в заголовке, потому что спрашивают её двое и из разных мест:
/// сам замок — когда строит, и лес — когда решает, где не расти.
constexpr i32 CASTLE_HALF = 34;

/// Замок в супер-чанке (sx, sz), если он там есть.
CastleSite castleAt(i32 superX, i32 superZ, u64 worldSeed,
                    const TerrainGenerator* terrain);

/// Логово, накрывающее точку, или пустое.
///
/// Перебирает соседние супер-чанки: радиус логова меньше шага сетки,
/// но центр смещён, и точка у края ячейки попадает в логово соседа.
LairSite lairCovering(i32 wx, i32 wz, u64 worldSeed,
                      const TerrainGenerator* terrain);

