namespace world {

struct ChunkCoord {
    i32 x, z;
    bool operator==(const ChunkCoord& o) const { return x == o.x && z == o.z; }
};
struct ChunkCoordHash {
    size_t operator()(const ChunkCoord& c) const noexcept {
        u64 h = (u64)(u32)c.x | ((u64)(u32)c.z << 32);
        return (size_t)(h * 0x9E3779B97F4A7C15ULL);
    }
};

/// Callback для перехвата модификаций блоков.
/// Устанавливается SaveManager'ом для записи в WorldDeltaStore.
///
/// oldId — блок, стоявший на месте до записи; UNKNOWN, если чанк ещё
/// не сгенерирован и прежний блок неизвестен. По нему хранилище узнаёт,
/// что игрок вернул клетку к тому, что было, и правку можно забыть.
using BlockModifyCallback =
    std::function<void(i32 wx, i32 wy, i32 wz, u16 newId, u16 oldId)>;

/// Источник правок игрока для только что сгенерированного чанка.
///
/// Зовётся из задачи генерации, под уникальным замком вокселей чанка,
/// сразу после того, как мир положил в него рельеф. Так правки
/// переживают выгрузку: чанк, ушедший из памяти и построенный заново,
/// снова получает их — а не только в момент загрузки сохранения.
///
/// Зовётся из рабочих потоков: источник обязан быть потокобезопасным.
using ChunkDeltaSource = std::function<void(ChunkCoord coord, Chunk& chunk)>;

/// Соседи чанка, удерживаемые владеющими ссылками: пока объект жив,
/// ни один из чанков не может быть выгружен из-под задачи меширования.
struct NeighborLease {
    std::shared_ptr<Chunk> nx, px, nz, pz;
    ChunkNeighbors view() const {
        ChunkNeighbors n;
        n.nx = nx.get(); n.px = px.get();
        n.nz = nz.get(); n.pz = pz.get();
        return n;
    }
};

class ChunkManager;

/// Готовый меш чанка.
struct MeshReady {
    std::shared_ptr<Chunk> chunk;
};

/// Курсор чтения вокселей.
///
/// Почти вся цена ChunkManager::getVoxel — это не чтение памяти, а
/// обвязка вокруг него: поиск чанка в хэш-таблице и два захвата
/// разделяемых замков на каждый воксель. Замер на хосте:
/// сорок пять наносекунд через менеджер против одной, когда чанк уже
/// найден и замок уже взят. Пятьдесят раз.
///
/// Для одиночного чтения это неважно, а поиск пути, столкновения и
/// читают воксели тысячами за кадр, почти всегда
/// подряд и почти всегда в одном и том же чанке. Курсор запоминает
/// последний чанк и держит его замок, пока читают из него же; при
/// переходе в соседний чанк — переоткрывает.
///
/// Живёт коротко, в пределах одной операции: пока курсор существует,
/// он держит разделяемый замок на вокселях чанка, а значит
/// откладывает изменение блоков в нём. Заводить его надолго и тем
/// более хранить в поле нельзя.
class VoxelReader {
public:
    explicit VoxelReader(const ChunkManager& mgr) : mgr_(&mgr) {}

    /// Тот же ответ, что у ChunkManager::getVoxel, включая правила для
    /// краёв мира и для ещё не сгенерированных чанков.
    u16 at(i32 wx, i32 wy, i32 wz);

    bool isSolid(i32 wx, i32 wy, i32 wz);

    /// Высота поверхности в колонке — та же, что у
    /// generator().surfaceHeight(), но взятая из уже сгенерированного
    /// чанка, а не посчитанная заново по шуму. Если чанка нет,
    /// считает генератором.
    ///
    /// Здесь, а не в ChunkManager, по той же причине, по которой
    /// здесь живёт чтение вокселей: тот, кто спрашивает высоту,
    /// спрашивает её сотнями подряд и почти всегда в одном чанке, а
    /// курсор уже держит и чанк, и его замок.
    ///
    /// Сейчас в игре не зовётся ниоткуда: единственным потребителем
    /// была рассадка травы. Оставлено намеренно — это единственный
    /// быстрый способ узнать высоту поверхности на ходу, генератор
    /// на том же запросе стоит в двести раз дороже.
    i32 surfaceAt(i32 wx, i32 wz);

    /// Отпустить чанк и его замок; следующее чтение откроет заново.
    ///
    /// Звать перед любым вызовом, который сам полезет в менеджер
    /// (спавн, физика, getVoxel): иначе порядок замков выходит
    /// «воксели → таблица чанков», обратный обычному «таблица →
    /// воксели», а повторный разделяемый захват того же замка при
    /// ждущем писателе на libc++ (Android) — самоблокировка.
    void release() {
        lk_ = std::shared_lock<std::shared_mutex>{};
        chunk_.reset();
        haveChunk_ = false;
        valid_ = false;
    }

private:
    void reopen(i32 cx, i32 cz);

    const ChunkManager* mgr_ = nullptr;
    std::shared_ptr<Chunk> chunk_;          ///< держим, чтобы не выгрузили
    std::shared_lock<std::shared_mutex> lk_;
    i32  cx_ = 0, cz_ = 0;
    bool haveChunk_ = false;                ///< чанк найден и сгенерирован
    bool valid_ = false;                    ///< cx_/cz_ вообще что-то значат
};

/// Связь фоновых задач с менеджером, переживающая сам менеджер.
///
/// Задача живёт дольше, чем гарантированно живёт ChunkManager: она
/// может спокойно лежать в очереди планировщика, когда менеджер уже
/// разрушен. Дождаться её разрушение умеет только пока планировщик
/// крутится, а значит не умеет:
///
///   * когда планировщик остановили раньше мира — деструктор пишет об
///     этом в журнал и идёт дальше, НЕ дождавшись;
///   * когда задачи не уложились в пять секунд — то же самое.
///
/// В обоих случаях в очереди оставались JobCtx с сырым указателем на
/// освобождённую память, и первый же запуск планировщика их выполнял.
/// В проверках это воспроизводилось падением в десяти прогонах из
/// десяти; в приложении не воспроизводилось только потому, что
/// порядок вызовов был выверен вручную и записан в комментарии.
///
/// Теперь задача держит владеющую ссылку на этот объект и первым
/// делом спрашивает его, есть ли ещё менеджер.
struct JobHost {
    std::atomic<bool> alive{true};      ///< менеджер ещё существует
    std::atomic<u32>  inFlight{0};      ///< поставленных и не доигранных задач
};

class ChunkManager {
public:
    explicit ChunkManager(u64 seed, i32 viewDistance = 8);
    ~ChunkManager();

    /// Возвращает чанк, при необходимости ставя его в очередь генерации.
    /// Владеющий указатель: чанк переживёт выгрузку, пока держат ссылку.
    std::shared_ptr<Chunk> getChunk(i32 cx, i32 cz);

    /// Чанк только если он уже загружен; генерацию не запускает.
    std::shared_ptr<Chunk> findChunk(i32 cx, i32 cz) const;

    void update(const glm::vec3& playerPos);

    /// Забирает чанки, у которых появились новые меши для выгрузки на GPU.
    /// Забирает готовые меши, но не больше maxCount за раз: остальные
    /// подождут следующего кадра. При загрузке мира и при быстром
    /// перемещении их приезжает по несколько десятков сразу, а каждый
    /// стоит сборки вершин и копии в видеопамять — без ограничения
    /// это заметный провал кадра ровно там, где игрок смотрит по
    /// сторонам. Ноль означает «все».
    std::vector<MeshReady> pollMeshesReady(usize maxCount = 0);

    /// Возвращает меш в очередь выгрузки.
    ///
    /// Забрать меш из очереди и не выгрузить его — это не редкость и
    /// не сбой: пакет передачи может не открыться, staging-пул может
    /// кончиться на пике загрузки мира, буфер может не создаться.
    /// Раньше такой чанк выручал рендер: он видел, что уровня нет, и
    /// заказывал его заново. Теперь уровней нет, и рендер узнаёт о
    /// чанке ТОЛЬКО из этой очереди — значит, потерянный меш не
    /// вернётся никогда, а на его месте останется дыра в ландшафте до
    /// следующей правки блока по соседству.
    ///
    /// Заново мешировать при этом нечего: квады построены и лежат в
    /// чанке. Нужно ровно одно — снова встать в очередь.
    void requeueMesh(const std::shared_ptr<Chunk>& chunk);

    /// ---- Управление вокселями ----
    void setVoxel(i32 wx, i32 wy, i32 wz, u16 block);
    u16  getVoxel(i32 wx, i32 wy, i32 wz) const;

    /// ---- Перехват изменений блоков (Phase 11) ----
    void setBlockModifyCallback(BlockModifyCallback cb) {
        std::lock_guard lk(callbackMtx_);
        blockModifyCb_ = std::move(cb);
    }

    /// ---- Правки игрока при генерации ----
    ///
    /// Мир хранит только то, что игрок изменил; всё остальное
    /// восстанавливается из зерна. Источник правок подключается сюда,
    /// и каждый чанк — впервые или после выгрузки — строится уже с
    /// ними.
    void setChunkDeltaSource(ChunkDeltaSource src) {
        std::lock_guard lk(callbackMtx_);
        deltaSource_ = std::move(src);
    }

    /// Построить заново все загруженные чанки: из зерна и текущих
    /// правок. Нужен загрузке сохранения — у загруженных чанков в
    /// вокселях лежат правки прежней сессии, которых в сейве может и
    /// не быть. Чанки, которых в памяти нет, трогать незачем: они
    /// получат правки, когда понадобятся.
    void regenerateLoaded();

    /// ---- Выгрузка чанков ----
    /// Чанки дальше радиуса (в чанках) от игрока. По умолчанию —
    /// обычный круг с гистерезисом, то есть дальность прорисовки
    /// плюс два.
    ///
    /// Радиус — довод, а не константа, ради нехватки памяти: когда
    /// система просит освободить её, единственное, что у мира есть
    /// отдать, — это дальние чанки, и отдавать их надо сразу и
    /// много, а не по обычному кругу.
    std::vector<ChunkCoord> collectUnloadCandidates(const glm::vec3& playerPos,
                                                    i32 radiusChunks = -1);
    void removeChunks(const std::vector<ChunkCoord>& coords);

    // ============================================================
    // Бюджет памяти на загруженный мир
    // ============================================================
    //
    // Раньше объём мира в памяти определялся ТОЛЬКО дальностью
    // прорисовки: сколько чанков попало в круг, столько и лежит, а
    // сколько это мегабайт — не спрашивал никто. При дальности 12 круг
    // держит около 450 чанков, то есть 115 МБ одних вокселей; на
    // планшете дальность больше, и предела не было вовсе. Телефон в
    // этот момент присылает APP_CMD_LOW_MEMORY, и разговор с системой
    // начинается уже тогда, когда она готова убить процесс.
    //
    // Теперь есть потолок, и мир держится под ним сам: всё, что сверху,
    // выгружается начиная с самых дальних чанков.
    //
    /// Резидентный размер одного чанка. Считается от типа, а не
    /// записан числом: изменится CHUNK_SIZE_Y или тип вокселя —
    /// изменится и он, без правки бюджета.
    static constexpr usize CHUNK_BYTES = sizeof(Chunk);

    /// Потолок по умолчанию: 512 МБ.
    static constexpr usize DEFAULT_MEMORY_BUDGET = 512ull * 1024ull * 1024ull;

    void  setMemoryBudget(usize bytes) { memoryBudget_ = bytes; }
    usize memoryBudget() const         { return memoryBudget_; }

    /// Сколько памяти занимают загруженные чанки прямо сейчас.
    usize residentBytes() const { return loadedChunks() * CHUNK_BYTES; }

    /// Сколько чанков влезает в бюджет.
    usize chunkCapacity() const {
        return memoryBudget_ / (CHUNK_BYTES ? CHUNK_BYTES : 1);
    }

    /// Чанки, которые надо выгрузить, чтобы уложиться в бюджет:
    /// самые дальние от игрока, ровно столько, сколько лишних.
    ///
    /// Отдельным списком, а не выгрузкой на месте: меши этих чанков
    /// лежат в видеопамяти, и забыть их обязан ещё и рендер. Кто
    /// вызвал — тот и проводит их по общему пути выгрузки.
    std::vector<ChunkCoord> collectOverBudget(const glm::vec3& playerPos) const;

    void setViewDistance(i32 d) { viewDistance_ = d; }
    i32  viewDistance() const   { return viewDistance_; }
    u64  seed() const { return seed_; }

    const TerrainGenerator& generator() const { return gen_; }

    /// Положение камеры: по нему идёт потоковая загрузка.
    void setCameraPosition(const glm::vec3& p) {
        cameraX_.store(p.x, std::memory_order_relaxed);
        cameraY_.store(p.y, std::memory_order_relaxed);
        cameraZ_.store(p.z, std::memory_order_relaxed);
        cameraKnown_.store(true, std::memory_order_release);
    }
    usize loadedChunks() const;

    /// Координаты всех загруженных чанков.
    ///
    /// Спрашивает смена мира: меши старых чанков лежат в видеопамяти,
    /// и забыть их рендер обязан ПОИМЁННО — иначе в новом мире по тем
    /// же координатам покажется прежний рельеф.
    std::vector<ChunkCoord> loadedCoords() const;

    /// Сгенерирован ли чанк, накрывающий точку. Пока нет, мир о ней
    /// ничего не знает: двигать в нём что-либо бессмысленно и вредно.
    bool isReadyAt(i32 wx, i32 wz) const;
    usize pendingJobs() const { return host_->inFlight.load(std::memory_order_relaxed); }

private:
    /// Контекст задачи владеет чанком: задача не может застать его
    /// уничтоженным, даже если игрок ушёл и чанк выгружен.
    struct JobCtx {
        /// Спрашивается ПЕРВЫМ делом: mgr можно трогать, только если
        /// alive ещё держится.
        std::shared_ptr<JobHost> host;
        ChunkManager*          mgr = nullptr;
        std::shared_ptr<Chunk> chunk;
        ChunkCoord             coord{};
        u64                    version = 0;
        /// Номер этого заказа (Chunk::meshSeq на момент постановки).
        /// По нему задача узнаёт, не устарела ли она.
        u64                    meshSeq = 0;
    };

    /// Сколько новых чанков заводим за один update().
    ///
    /// Чанк — это четверть мегабайта вокселей, и цена его появления
    /// не в аллокации (четыре микросекунды), а в первом касании
    /// страниц: их обнуляет ядро. Замер: двести созданных и
    /// удержанных чанков — шестнадцать с половиной миллисекунд.
    /// Восемь за кадр: круг из двух сотен чанков нарастает за
    /// четверть секунды, от игрока наружу. Замер на хосте — провал
    /// потоковой загрузки при рывке через полмира упал с устойчивых
    /// 19-21 мс до медианных двух-пяти, размазанных по двум десяткам
    /// кадров.
    ///
    /// Само число подобрано грубо и намеренно. Значения 4, 8 и 12 на
    /// хосте не различаются: разброс между прогонами одного и того же
    /// значения больше разницы между значениями. Выбирать точнее надо
    /// на устройстве, где память медленнее, а ядер меньше.
    static constexpr u32 MAX_NEW_CHUNKS_PER_UPDATE = 8;

    /// Смещение в круге потоковой загрузки вместе с квадратом
    /// расстояния — по нему обход и упорядочен.
    struct StreamOffset { i32 dx, dz, distSq; };

    /// Порядок обхода круга: считается один раз на дальность
    /// прорисовки, а не каждый кадр.
    void rebuildStreamOrder();

    void enqueueGenerate(ChunkCoord coord);
    /// Ставит задачу меширования чанка. Номер заказа фиксируется
    /// здесь и уезжает в задаче: по нему она узнаёт, не устарела ли.
    void enqueueMesh(ChunkCoord coord);

    NeighborLease gatherNeighbors(i32 cx, i32 cz) const;

    static void jobGenerate(void* data);
    static void jobMesh(void* data);

    /// Плитки гидросети — заранее, в фоне.
    ///
    /// Плитка водосборов стоит десятки миллисекунд на хосте и сотни на
    /// телефоне, и считается один раз на две тысячи блоков пути. Если
    /// ждать, пока её спросит генерация первого чанка, все рабочие
    /// потоки встанут на ней разом — ровно тогда, когда игрок видит
    /// край мира. Поэтому плитки, к которым игрок подходит, заказываются
    /// заранее, пока до их чанков ещё сотни блоков.
    void prefetchHydrology(const glm::vec3& playerPos);
    struct HydroJob {
        std::shared_ptr<JobHost> host;
        ChunkManager* mgr = nullptr;
        i32 tx = 0, tz = 0;
    };
    static void jobHydro(void* data);
    /// Уже заказанные плитки. Трогает только update(), то есть главный
    /// поток.
    std::vector<std::pair<i32, i32>> hydroRequested_;
    i32 hydroCheckedCx_ = 0x7FFFFFFF, hydroCheckedCz_ = 0x7FFFFFFF;

    u64 seed_;
    i32 viewDistance_;
    /// Потолок резидентной памяти мира. См. setMemoryBudget.
    usize memoryBudget_ = DEFAULT_MEMORY_BUDGET;
    /// Положение камеры: от него меряется порядок потоковой
    /// загрузки. Раньше здесь лежал чанк игрока — величина грубее
    /// той, которой меряет рендер.
    std::atomic<f32> cameraX_{0.f}, cameraY_{0.f}, cameraZ_{0.f};
    /// Пока рендер не прислал камеру (первый кадр после загрузки),
    /// её заменяет позиция игрока.
    std::atomic<bool> cameraKnown_{false};
    TerrainGenerator gen_;

    std::unordered_map<ChunkCoord, std::shared_ptr<Chunk>, ChunkCoordHash> chunks_;
    mutable std::shared_mutex chunksMtx_;

    std::mutex                                readyMtx_;
    std::vector<MeshReady>                    meshesReady_;

    /// Задачи генерации и меширования вместе: деструктор ждёт их все,
    /// иначе воркер обратится к уничтоженному ChunkManager. Счётчик
    /// живёт в JobHost, а не здесь: задача уменьшает его уже после
    /// того, как менеджера может не быть.
    std::shared_ptr<JobHost>  host_ = std::make_shared<JobHost>();

    /// Круг вокруг игрока в порядке возрастания расстояния.
    ///
    /// Здесь же раньше лежала карта lastAccess_: update() писал в неё
    /// отметку на каждый чанк круга каждый кадр — три сотни вставок
    /// в хэш-таблицу под отдельным замком, — а не читал её НИКТО.
    /// Выгрузка чанков решает по расстоянию, а не по давности. Вместе
    /// с картой ушёл и счётчик кадров, который вёлся только ради неё.
    std::vector<StreamOffset> streamOrder_;
    i32                       streamOrderFor_ = -1;   ///< для какой дальности построен

    /// Callback (Phase 11)
    BlockModifyCallback       blockModifyCb_;
    ChunkDeltaSource          deltaSource_;
    mutable std::mutex        callbackMtx_;

};

} // namespace world
