/**
 * @file debug_scene.h
 * @brief Минимальная детерминированная сцена для сверки рендеров.
 */
#pragma once
#include "chunk.h"

namespace world {

/// Минимальная сцена: ровная земля, один поднятый блок, одна лесенка,
/// одна вода, одно дерево, и всё.
///
/// Смысл в том, что её строит ОДНА функция, а рисуют оба рендера:
/// офлайн-проверка на хосте и игра на устройстве. Пока их кадры не
/// сойдутся пиксель в пиксель, сравнивать что-то на полном мире
/// бессмысленно — там слишком много движущихся частей, чтобы отличить
/// ошибку рендера от ошибки данных.
///
/// Сцена целиком помещается в один чанк 32x32 и НЕ зависит ни от
/// зерна мира, ни от шума, ни от порядка загрузки соседей. Чанки
/// вокруг нулевого заполняются той же ровной землёй, чтобы у
/// центрального были честные соседи и на стыках не было швов.
void buildMinimalScene(Chunk& c);

/// Где стоит камера и куда смотрит, когда сцена включена.
/// Числа одинаковы на хосте и на устройстве — иначе сравнивать нечего.
constexpr f32 SCENE_EYE_X   = 16.5f;
constexpr f32 SCENE_EYE_Y   = 44.0f;
constexpr f32 SCENE_EYE_Z   = -18.0f;
constexpr f32 SCENE_YAW     = 0.0f;    ///< 0 — взгляд вдоль +Z
constexpr f32 SCENE_PITCH   = -0.50f;

/// Точка выбрана так, чтобы в кадр разом попали все приметы и ни одна
/// не закрывала другую: дерево слева вблизи, лесенка по центру, вода
/// справа, одиночный блок слева вдали.

/// Освещение и время сцены. Пока солнце ходит по небу, а трава
/// качается от времени кадра, два рендера не сойдутся никогда: сцена
/// обязана быть неподвижной.
constexpr f32 SCENE_SUN_X   = 0.35f;
constexpr f32 SCENE_SUN_Y   = 0.78f;
constexpr f32 SCENE_SUN_Z   = 0.25f;
constexpr f32 SCENE_SKY_R   = 0.55f;
constexpr f32 SCENE_SKY_G   = 0.72f;
constexpr f32 SCENE_SKY_B   = 0.92f;
constexpr f32 SCENE_SKY_LIGHT   = 1.0f;
constexpr f32 SCENE_TIME_OF_DAY = 0.3f;
constexpr f32 SCENE_TIME_SEC    = 0.0f;
/// Фиксированный шаг кадра. Настоящий dt пляшет от загрузки телефона,
/// и любая система, которая на него смотрит, делала бы сцену разной от
/// запуска к запуску.
constexpr f32 SCENE_FIXED_DT    = 1.0f / 60.0f;

/// Отметки сцены — на них ссылается разбор кадра.
constexpr i32 SCENE_GROUND_Y = 32;     ///< верх ровной земли
constexpr i32 SCENE_BLOCK_X  = 8;      ///< одиночный поднятый блок
constexpr i32 SCENE_BLOCK_Z  = 20;
constexpr i32 SCENE_SLOPE_X0 = 12;     ///< лесенка: x от X0 вверх
constexpr i32 SCENE_SLOPE_X1 = 19;
constexpr i32 SCENE_POOL_X0  = 22;     ///< вода
constexpr i32 SCENE_POOL_X1  = 29;
constexpr i32 SCENE_POOL_Z0  = 16;
constexpr i32 SCENE_POOL_Z1  = 23;
constexpr i32 SCENE_TREE_X   = 5;      ///< дерево
constexpr i32 SCENE_TREE_Z   = 6;

} // namespace world
