namespace world {

/// Биом определяется по климату (температура, влажность) и высоте.
/// Плавная интерполяция между соседними биомами через blendedHeight.
enum BiomeId : u8 {
    Ocean = 0,
    Beach,
    Plains,
    Forest,
    Taiga,
    Desert,
    Savanna,
    Tundra,
    Mountains,
    Swamp,
    Volcanic,
    /// Чёрный лес: зловещая земля, где живут только чудовища.
    ///
    /// Не климат, а порча: выделяется отдельным шумовым полем поверх
    /// обычной классификации, поэтому попадается и среди равнин, и
    /// среди тайги. Лес там вдвое гуще обычного и весь из сухостоя,
    /// земля голая, и водятся в нём только враждебные твари — днём
    /// тоже.
    Blight,
    BIOME_COUNT
};

enum class TreeType : u8 {
    None,
    Oak,       // широкий blob
    Pine,      // конус
    Palm,      // зонтик
    Cactus,    // без листвы
    Dead       // сухое дерево
};

struct BiomeDef {
    const char* name;
    u16 surfaceBlock;
    u16 subsurfaceBlock;    // 2-4 блока под поверхностью
    u16 stoneBlock;
    u16 liquidBlock;        // вода/лава/нет
    f32 treeDensity;        // деревьев на чанк (в среднем)
    TreeType treeType;
    i8 baseHeightOffset;    // смещение базовой высоты (может быть ниже базы)
    f32 temperature;        // справочная
};

// ============================================================
// Домашняя околица
// ============================================================
//
// Где игрок появляется впервые — вопрос ГЕНЕРАЦИИ, а не перебора
// точек. Перебор умеет отвергнуть плохое место, но не умеет сделать
// хорошее: если вокруг на сто блоков океан, вулкан или хребет, он
// честно переберёт всё и не найдёт ничего.
//
// Поэтому климат у начала координат подтягивается к пригодному для
// жизни: суша выше уровня моря, пологий рельеф, никакой порчи и
// никакого поднятия коры. Какой именно выйдет околица — решает
// зерно: чистое поле, густой лес, редколесье или сосняк. Опасного в
// этом списке нет по построению, а не по проверке.
//
// Подтяжка НЕ полная (см. HOME_WEIGHT): доля собственного шума мира
// остаётся, иначе околица вышла бы столом. И она сходит на нет к
// HOME_FADE_RADIUS — дальше мир такой, каким его сделало зерно.

/// Радиус, внутри которого подтяжка действует в полную силу.
/// Перебор точки появления идёт по области 100x100, то есть целиком
/// помещается внутрь.
constexpr f32 HOME_FULL_RADIUS = 96.f;

/// Радиус, за которым подтяжки нет вовсе.
constexpr f32 HOME_FADE_RADIUS = 448.f;

/// Какая доля климата у начала координат назначена, а не выросла.
///
/// Не единица намеренно: оставшаяся доля собственного шума даёт
/// околице рельеф. При единице все миры начинались бы на одинаковой
/// ровной площадке.
constexpr f32 HOME_WEIGHT = 0.85f;

/// Каким бывает начало пути. Ровно четыре, и все безопасные.
enum class HomeKind : u8 { Plains = 0, Forest, Savanna, Taiga, Count };

/// Вес подтяжки на расстоянии d блоков от начала координат.
f32 homeWeight(f32 d);

/// BiomeField — климатические поля через Simplex-шум.
/// Пять fBm-полей (континенты, температура, влажность, эрозия,
/// пики) считаются один раз на колонку, см. fields()/classify().
class SimplexNoise;  // fwd

class BiomeField {
public:
    explicit BiomeField(u64 seed);
    ~BiomeField();
    BiomeField(const BiomeField&) = delete;
    BiomeField& operator=(const BiomeField&) = delete;

    struct Sample {
        BiomeId biome;
        f32     temperature;   // -1..1
        f32     humidity;      // -1..1
        f32     continent;     // -1..1 (океан → суша)
        f32     erosion;       //  0..1 (0 = крутые горы, 1 = равнина)
        f32     peaks;         //  0..1
        /// «Порча»: отдельное низкочастотное поле, по которому
        /// размечается Чёрный лес. Поле было заведено в генераторе
        /// с самого начала и не спрашивалось ни разу — шум считался
        /// впустую.
        f32     weird;         // -1..1
        /// Поднятие коры: где земля вздыблена в хребет, 0..1.
        ///
        /// Отдельное поле, а не совпадение хвостов. Пока гора была
        /// местом, где ОДНОВРЕМЕННО высок пик и низка эрозия и высок
        /// континент, гор в мире не было вовсе: на полумиллионе
        /// колонок ни одной выше восьмидесяти двух. Три колокола не
        /// сходятся в своих хвостах — их произведение и есть ноль.
        ///
        /// Хребет же — не совпадение, а СВОЁ поле, ровно как порча у
        /// Чёрного леса: где оно высоко, там горы, и высоко оно
        /// полосами, потому что хребты полосами и идут.
        f32     uplift;
        f32     heightMod;     // модификатор высоты (-20..+40)
    };

    /// Полный запрос: шум + классификация. Эквивалентен
    /// classify(fields(x, z), x, z, surfaceY).
    Sample sample(i32 x, i32 z, i32 surfaceY) const;

    /// Только шумовые поля — они не зависят от высоты поверхности.
    /// Выделено отдельно, потому что высота сама считается из них:
    /// иначе один и тот же шум пришлось бы считать дважды.
    Sample fields(i32 x, i32 z) const;

    /// Классификация биома по готовым полям и фактической высоте.
    /// Шум не трогает — только пороги.
    void classify(Sample& s, i32 surfaceY) const;

    const BiomeDef& def(BiomeId b) const;

    /// Какая околица досталась этому миру. Спрашивают проверки: иначе
    /// «в начале всегда живётся» можно подтвердить только глазами.
    HomeKind home() const;

private:
    struct Impl;
    // PIMPL чтобы не тащить шум в заголовок. Раньше был голый
    // указатель без деструктора: каждый мир (а мир пересоздаётся при
    // каждом возврате в приложение) терял несколько КБ шумовых таблиц.
    std::unique_ptr<Impl> impl_;
};

} // namespace world
