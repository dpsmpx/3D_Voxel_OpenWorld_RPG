namespace world {

/// 3D Simplex Noise (алгоритм Gustavson, public domain).
/// Детерминирован по seed: одна и та же пара (seed, точка) всегда
/// даёт один результат — на этом держится воспроизводимость мира.
///
/// ---- Зерно смещает и ТОЧКУ ВЫБОРКИ, а не только градиенты ----
///
/// Раньше зерно перемешивало одну лишь таблицу перестановок, а
/// решётка симплексов у всех миров стояла на одном месте — началом в
/// точке (0,0,0). У симплекс-шума в узле решётки вклад этого узла
/// равен нулю по построению (смещение до него нулевое, и скалярное
/// произведение с градиентом тоже), а соседние узлы туда не достают.
/// То есть sample3D(0,0,0) == 0 ПРИ ЛЮБОЙ перестановке, а значит и
/// при любом зерне.
///
/// Мир платил за это дорого. Все шесть климатических полей читались
/// в начале координат нулём, «хребет» в biome.cpp ставится по узкой
/// полосе ВОКРУГ НУЛЯ шума — и получал ровно единицу. Замер до
/// правки: восемь зёрен из восьми давали в точке (0,0) uplift 1.000,
/// высоту 78 и биом Mountains. Игрок появлялся на гребне
/// максимального хребта в каждом мире, сколько бы миров ни создал.
///
/// Смещение невелико намеренно: координаты полей умножаются на
/// сотые доли, и большое смещение съело бы точность float там, где
/// шаг между соседними блоками и так измеряется единицами ulp.
///
/// Многослойная генерация (высота, климат, пещеры, руды) живёт в
/// TerrainGenerator, см. terrain.h.
class SimplexNoise {
public:
    explicit SimplexNoise(u64 seed = 0);

    /// Одиночная выборка, результат примерно в [-1, 1].
    f32 sample3D(f32 x, f32 y, f32 z) const;

    /// Двумерный срез трёхмерного шума.
    f32 sample2D(f32 x, f32 y) const { return sample3D(x, y, 0.0f); }

    /// fBm — сумма октав с затуханием амплитуды, нормирована к [-1, 1].
    f32 fbm3D(f32 x, f32 y, f32 z, u32 octaves,
              f32 lacunarity = 2.0f, f32 gain = 0.5f) const;

    /// Ridged-шум: 1 - |noise|, даёт хребты и связные туннели.
    f32 ridged3D(f32 x, f32 y, f32 z, u32 octaves,
                 f32 lacunarity = 2.0f, f32 gain = 0.5f) const;

    /// Доменное искажение: смещает точку выборки другим шумом.
    f32 warped3D(f32 x, f32 y, f32 z, f32 strength) const;

private:
    f32 grad(i32 hash, f32 x, f32 y, f32 z) const;

    u8 perm_[512];
    /// Смещение точки выборки, своё у каждого зерна. См. выше.
    f32 offX_ = 0.f, offY_ = 0.f, offZ_ = 0.f;
    static constexpr f32 F3 = 1.0f / 3.0f;
    static constexpr f32 G3 = 1.0f / 6.0f;
};

} // namespace world
