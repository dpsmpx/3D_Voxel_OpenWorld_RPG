/**
 * @file showcase.h
 * @brief Витрина: все сущности разом, детерминированно.
 */
#pragma once
#include "rig.h"
#include "locomotion.h"

namespace entity {

/// Одна модель на витрине.
struct ShowcaseSlot {
    const char* name  = "";
    const Rig*  rig   = nullptr;
    glm::vec3   pos{0};
    f32         yaw   = 0.f;
    anim::AnimState state{};
};

/// Сколько моделей помещается на витрине.
constexpr u8 SHOWCASE_MAX = 32;

/// Собрать витрину: каждая модель проекта, в ряд, в заданной позе.
///
/// Зачем это есть. Модели живут в разных местах — мобы в своём
/// реестре, NPC в своём, игрок отдельно, — и посмотреть на них разом
/// было негде. Ошибка вида «у этого вида ноги короче туловища»
/// видна только рядом с остальными; поодиночке она выглядит
/// замыслом.
///
/// Витрина ДЕТЕРМИНИРОВАННА: ни времени, ни случайности, ни зерна
/// мира. Два прогона дают одно и то же, иначе сравнивать нечего.
///
/// `phase` и `speedNorm` задают позу всему ряду сразу: так видно, что
/// походка ложится на разные скелеты одинаково.
///
/// Возвращает число заполненных слотов.
u8 buildShowcase(ShowcaseSlot* out, u8 outMax, f32 phase, f32 speedNorm);

/// Сколько коробок стоит вся витрина. Прямая мера цены моделей.
u32 showcaseBoxCount(f32 phase, f32 speedNorm);

} // namespace entity
