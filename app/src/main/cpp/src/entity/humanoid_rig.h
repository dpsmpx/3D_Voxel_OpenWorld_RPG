/**
 * @file humanoid_rig.h
 * @brief Оснастка двуногого: одна для NPC, стражи и игрока.
 */
#pragma once
#include "rig.h"

namespace entity {

/// Пропорции и цвета двуногого.
///
/// Всё задаётся ДОЛЯМИ роста, а не числами в метрах: тогда один
/// набор пропорций одинаково ложится и на приземистого кузнеца, и на
/// рослого стража, и на игрока. Цифры здесь — не украшение: именно
/// они решают, читается ли силуэт с игровой камеры.
struct HumanoidSpec {
    f32 height = 1.8f;          ///< от подошвы до макушки

    u32 bodyColor   = 0x808080FFu;
    u32 headColor   = 0xC0A080FFu;
    u32 accentColor = 0x606060FFu;

    /// Доли роста. Сумма ног, торса и головы даёт единицу.
    f32 legFrac   = 0.46f;      ///< подошва → бедро
    f32 torsoFrac = 0.30f;      ///< бедро → плечи
    f32 headFrac  = 0.24f;      ///< шея → макушка

    /// Ширина и глубина — тоже в долях роста.
    f32 shoulderFrac = 0.34f;   ///< ширина торса
    f32 depthFrac    = 0.20f;   ///< глубина торса
    f32 limbFrac     = 0.10f;   ///< толщина конечности

    /// Оружие в правой руке, доля роста. Ноль — безоружный.
    ///
    /// Часть оснастки, а не украшение рендера: стражник с мечом и
    /// стражник без меча обязаны отличаться на вид, иначе «дали
    /// оружие» видно только в таблице урона.
    f32 weaponFrac  = 0.f;
    f32 weaponThickFrac = 0.022f;
    u32 weaponColor = 0xC8CCD4FFu;
};

/// Собрать двуногого.
///
/// Иерархия: корень (подошва) → торс → голова, плечи, бёдра;
/// плечо → предплечье; бедро → голень. Конечности вращаются В
/// СУСТАВЕ — за это отвечает pivot, а не смещение коробки.
Rig humanoidRig(const HumanoidSpec& spec);

} // namespace entity
