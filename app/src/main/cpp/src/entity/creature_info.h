/**
 * @file creature_info.h
 * @brief Кто это существо: имя и цвет тела, как их видит игрок.
 */
#pragma once
#include "../core/types.h"
#include "../ecs/registry.h"
#include "rig.h"

namespace entity {

/// Цвет тела оснастки.
///
/// Торс, а при его отсутствии — самая крупная видимая часть. Это и
/// есть «цвет существа» в том смысле, в каком его видит игрок: у
/// волка это шкура, у Каменного стража — камень, у жителя — рубаха.
///
/// Чистая функция от оснастки: её можно проверить на любой модели
/// проекта, не собирая ни мира, ни реестра.
u32 bodyColor(const Rig& rig);

/// Цвет тела существа, кем бы оно ни было.
///
/// Оснастки живут в трёх разных местах — у мобов своя, у жителей
/// своя, у игрока третья, — и это ЕДИНСТВЕННОЕ место, где все три
/// сходятся ради одного ответа. Без него правило «осколки цвета
/// того, по кому ударили» пришлось бы писать заново на каждом
/// поводе.
///
/// Существо без оснастки даёт нейтральный серый: лучше блёклая
/// горсть, чем её отсутствие.
u32 creatureColor(ecs::Registry& reg, ecs::Entity e);

/// Как существо называется.
///
/// Здесь по той же причине, что и цвет: имена лежат в трёх разных
/// реестрах — мобов, жителей, игрока, — и вопрос «кого я сейчас бью»
/// не должен знать, в каком из трёх искать.
///
/// Возвращает указатель на строку реестра: она живёт до выхода из
/// игры, копировать её незачем. Существо без имени даёт пустую
/// строку, а не nullptr, — звать её можно прямо в отрисовку текста.
const char* creatureName(ecs::Registry& reg, ecs::Entity e);

} // namespace entity
