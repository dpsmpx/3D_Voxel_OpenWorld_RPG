#pragma once
#include "rig.h"

namespace entity {

/// Описание зверя.
///
/// Это ОПИСАНИЕ МОДЕЛИ, а не набор коробок со смещениями. Разница не
/// косметическая: плоский список коробок нельзя было ни согнуть в
/// суставе, ни дополнить ухом — слотов было ровно девять, с
/// зашитыми значениями. Отсюда и брались звери без ушей, без морды и
/// без рогов, отличавшиеся друг от друга только цветом и размером
/// параллелепипеда.
///
/// `height` — до макушки. Сборщик ставит голову так, чтобы макушка
/// пришлась ровно на эту высоту, поэтому рост модели совпадает с
/// ростом коллайдера ПО ПОСТРОЕНИЮ, а не по внимательности. Раньше
/// они расходились: у Каменного стража модель была 4.35 при
/// коллайдере 3.40 — почти на метр выше, чем то, во что попадают.
struct BeastSpec {
    f32 height     = 1.2f;    ///< подошва → макушка
    f32 bodyLength = 1.1f;    ///< торс по Z
    f32 bodyWidth  = 0.7f;    ///< торс по X
    f32 bodyDepth  = 0.6f;    ///< торс по Y

    f32 legLength  = 0.6f;
    f32 legThick   = 0.18f;
    u8  legPairs   = 2;       ///< 2 пары — зверь, 1 — птица

    f32 headSize   = 0.55f;
    f32 headWidth  = 0.55f;   ///< морда бывает уже черепа

    /// Приметы. Именно они и отличают овцу от волка, когда обе —
    /// коробка на четырёх ногах.
    f32 earSize    = 0.f;     ///< 0 — ушей нет
    f32 earLean    = 0.f;     ///< >0 торчат вверх, <0 висят
    f32 snoutLen   = 0.f;     ///< 0 — морды нет
    f32 hornLen    = 0.f;     ///< 0 — рогов нет
    f32 tailLength = 0.f;     ///< 0 — хвоста нет
    f32 tailThick  = 0.14f;
    f32 tailLift   = 0.f;     ///< угол подъёма хвоста, радианы

    u32 bodyColor   = 0xC0C0C0FFu;
    u32 headColor   = 0xC8C8C8FFu;
    u32 legColor    = 0x787878FFu;
    u32 accentColor = 0xE0A040FFu;   ///< клюв, рога, кончик хвоста
};

/// Собрать зверя.
///
/// Иерархия: корень (подошва) → торс → голова, уши, хвост, бёдра;
/// голова → морда, рога; бедро → голень.
Rig beastRig(const BeastSpec& spec);

} // namespace entity
