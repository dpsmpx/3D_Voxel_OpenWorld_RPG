#pragma once
#include "../core/types.h"
#include "../ecs/registry.h"
#include "damage.h"
#include <glm/glm.hpp>

namespace combat {

/// Сколько длится окно парирования, секунды.
///
/// Защита, поднятая раньше этого срока до попадания, ОТБИВАЕТ удар.
/// Поднятая позже — просто принимает его на себя.
///
/// Двести двадцать миллисекунд — меньше самого короткого замаха в
/// игре (гоблин, 260 мс). Это принципиально: парирование обязано
/// быть ответом на УВИДЕННЫЙ замах, а не заранее поднятой защитой.
/// Будь окно шире замаха, выгодно было бы жать блок вслепую.
constexpr f32 PARRY_WINDOW = 0.22f;

/// Во сколько выносливости обходится единица поглощённого урона.
///
/// Три: укус волка (4 урона, меч поглощает 0.7) стои́т восемь с
/// половиной из сотни, удар Каменного Стража — около сорока. То
/// есть волков можно держать на защите долго, а босса — два удара,
/// и на третий защиту пробьют. Ровно то соотношение, при котором
/// блок остаётся выходом против мелочи и не заменяет уклонение
/// против тяжёлого.
constexpr f32 GUARD_STAMINA_PER_DAMAGE = 3.0f;

/// Насколько медленнее идёт тот, кто держит защиту.
///
/// Это и есть постоянная цена блока: держать его сколько угодно
/// можно, но пока держишь — не убежишь и не догонишь.
constexpr f32 GUARD_SPEED_MULT = 0.45f;

/// Сколько оглушён тот, чью защиту пробили.
constexpr f32 GUARD_BREAK_STUN = 0.9f;

/// Сколько оглушён тот, чей удар отбили.
///
/// Чуть дольше пробития: отбить удар труднее, чем пробить защиту, и
/// награда обязана быть больше наказания. Оглушение ОБРЫВАЕТ замах
/// (см. mobs/mob_ai.cpp), поэтому отбитая тварь не просто стои́т —
/// она теряет весь начатый удар.
constexpr f32 PARRY_STAGGER = 1.1f;

/// Сектор защиты: полный угол, радианы. 2.2 — это ±63°.
///
/// Со спины и сбоку защиты нет. Иначе поднятый щит был бы строго
/// лучше всего остального: можно было бы встать в кольцо тварей и
/// держать кнопку.
constexpr f32 GUARD_ARC = 2.2f;

/// За сколько секунд защита встаёт и опускается в позе.
constexpr f32 GUARD_RAISE_TIME = 0.12f;

/// Сколько защита обязана ПРОБЫТЬ ОПУЩЕННОЙ, чтобы следующий подъём
/// снова давал окно парирования.
///
/// Без этого механика ломается одним пальцем: дробя кнопку, игрок
/// держал бы `raisedFor` у нуля постоянно — и КАЖДЫЙ удар приходился
/// бы в свежую защиту, то есть парировался. Выбор «блок или
/// парирование» исчез бы, остался бы один правильный ответ.
///
/// Треть секунды: дробь (пять-шесть кадров между нажатиями) окна не
/// получает, а честный «отпустил после блока — поднял на следующий
/// замах» получает с запасом. Самая частая серия в игре — у Полого
/// Владыки в ярости, и между его ударами шестьсот миллисекунд.
constexpr f32 PARRY_REARM_TIME = 0.35f;

/// Что случилось с ударом, пришедшим в защиту.
enum class GuardResult : u8 {
    None = 0,   ///< защиты не было, или удар пришёл мимо неё
    Parried,    ///< отбит: урона нет, бьющий открылся
    Blocked,    ///< принят: урон урезан, выносливость потрачена
    Broken,     ///< пробит: урон прошёл целиком, защитник оглушён
};

/// Состояние защиты. Компонент — значит, защищаться может кто
/// угодно, а не «игрок как особый случай».
struct GuardState {
    /// Поднята прямо сейчас.
    bool      up        = false;
    /// Сколько секунд держим. По нему и опознаётся парирование.
    f32       raisedFor = 0.f;
    /// Сколько секунд защита опущена. Копится, пока она внизу, и
    /// решает, даст ли следующий подъём окно парирования.
    f32       downFor   = 999.f;
    /// Даёт ли ТЕКУЩИЙ подъём окно парирования. Решается один раз,
    /// в момент подъёма, и не пересматривается: иначе «успел или
    /// нет» зависело бы от того, когда по тебе ударят.
    bool      armed     = false;
    /// Куда смотрит защита, XZ. У игрока — взгляд камеры, а не
    /// направление ходьбы: щит держат туда, куда смотрят.
    glm::vec3 facing{ 0.f, 0.f, 1.f };

    /// Исход последнего удара по защите. Забирается владельцем —
    /// тем же приёмом, каким игрок забирает отдачу камеры.
    GuardResult pending = GuardResult::None;

    /// Вспышка на защите: читается рендером, гаснет сама.
    f32 flash = 0.f;

    /// Насколько защита поднята в ПОЗЕ, 0..1.
    ///
    /// Отдельно от `up`: рука встаёт и опускается за время, иначе
    /// поза щёлкает между двумя положениями.
    f32 pose = 0.f;

    /// Успеет ли ещё отбить.
    bool parryReady() const {
        return up && armed && raisedFor < PARRY_WINDOW;
    }

    GuardResult takeResult() {
        const GuardResult r = pending;
        pending = GuardResult::None;
        return r;
    }

    /// Продвинуть время.
    /// @param want держит ли владелец защиту в этом кадре
    /// @param dir  куда он смотрит
    void tick(f32 dt, bool want, const glm::vec3& dir);
};

/// Пропустить удар через защиту цели.
///
/// Зовётся из applyDamage ДО сопротивлений и ДО уворота и правит
/// `dmg.amount` на месте. Возвращает исход — его же кладёт в
/// GuardState::pending для владельца.
GuardResult resolveGuard(ecs::Registry& reg,
                         ecs::Entity target,
                         DamageInstance& dmg);

/// Какую долю урона держит оружие в руке. Из реестра оружия.
f32 guardFractionOf(ecs::Registry& reg, ecs::Entity e);

} // namespace combat
