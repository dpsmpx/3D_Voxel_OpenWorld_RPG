/**
 * @file swing.h
 * @brief Замах: одно правило удара для всех, кто бьёт.
 */
#pragma once
#include "../core/types.h"
#include "../entity/locomotion.h"
#include <algorithm>

namespace combat {

/// За сколько гаснет проводка руки после попадания, секунды.
///
/// Не мгновенно и не долго: рука обязана пройти СКВОЗЬ цель, иначе
/// удар выглядит остановленным о воздух. Четверть секунды — время,
/// за которое взгляд успевает увидеть, что удар состоялся, и не
/// успевает заскучать.
constexpr f32 SWING_FOLLOW_TIME = 0.26f;

/// Состояние замаха.
///
/// Удар — не мгновение, а три такта: замах, попадание, проводка.
/// У игрока так было с самого начала (combat::WeaponState), у тварей
/// и жителей — нет: урон, звук и поза приходили в один и тот же
/// кадр, ровно когда истекал откат. Увидеть удар было нельзя, а
/// значит нельзя было ни отойти, ни рвануть в сторону — и весь
/// инструментарий противодействия (рывок, выносливость, кадры
/// неуязвимости, отбрасывание) лежал без применения.
///
/// Общий ТИП для тварей и жителей, а не общий тип со всеми: у игрока
/// машина состояний уже правильная и завязана на стоимость маны,
/// выносливости, Резонанс и снаряды. Сводить их в одну структуру —
/// большой рефактор ради строчки экономии. Общим здесь сделано
/// ПРАВИЛО («удар начинается раньше, чем попадает») и ДВИЖЕНИЕ
/// (anim::attackPose), а это как раз то, что видит игрок.
struct SwingState {
    f32 windupLeft  = 0.f;   ///< сколько осталось до попадания
    f32 windupTotal = 0.f;   ///< сколько длится замах целиком
    f32 follow      = 0.f;   ///< 0..1, рука идёт сквозь цель

    /// Замахивается прямо сейчас.
    bool winding() const { return windupLeft > 0.f; }

    /// Занят ударом: либо замахивается, либо ещё не опустил руку.
    bool busy() const { return windupLeft > 0.f || follow > 0.f; }

    /// Начать замах. Нулевой длительности не бывает: удар без замаха
    /// — это ровно то, что чинится.
    void begin(f32 windupTime) {
        windupTotal = windupTime > 0.02f ? windupTime : 0.02f;
        windupLeft  = windupTotal;
        follow      = 0.f;
    }

    /// Прервать замах, не нанеся удара. Оглушённый удара не доводит,
    /// и мёртвый тоже.
    void cancel() {
        windupLeft  = 0.f;
        windupTotal = 0.f;
    }

    /// Продвинуть время.
    /// @return true РОВНО в тот кадр, когда замах дошёл до цели.
    bool tick(f32 dt) {
        if (follow > 0.f)
            follow = std::max(0.f, follow - dt / SWING_FOLLOW_TIME);

        if (windupLeft <= 0.f) return false;

        windupLeft -= dt;
        if (windupLeft > 0.f) return false;

        windupLeft = 0.f;
        follow     = 1.f;
        return true;
    }

    /// Положение руки на дуге удара для anim::AnimState::attack.
    ///
    /// Замах идёт с ЗАМЕДЛЕНИЕМ: рука быстро уходит назад и там
    /// ЖДЁТ. Ожидание и есть телеграф — по равномерному отводу
    /// момент удара не прочитать, а по «отвёл и держит» прочитать
    /// можно. Отсюда ease-out, а не прямая.
    f32 pose() const {
        if (windupLeft > 0.f && windupTotal > 0.f) {
            const f32 left  = windupLeft / windupTotal;   // 1 → 0
            const f32 drawn = 1.f - left * left;          // быстро, потом держит
            return -drawn;
        }
        return follow;
    }
};

} // namespace combat
