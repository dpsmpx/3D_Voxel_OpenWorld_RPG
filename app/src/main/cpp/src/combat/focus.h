#pragma once
#include "../core/types.h"
#include "../ecs/registry.h"

namespace combat {

/// С кем у игрока размен.
///
/// Не «выбранная цель» и не захват прицела: выбирать не надо, игра
/// сама знает, кого игрок бьёт и кто бьёт его. Поэтому здесь нет ни
/// кнопки, ни правила «ближайший в конусе» — только память о
/// последнем размене.
struct FocusTarget {
    /// Идентификатор сущности, 0 — никого.
    ///
    /// Число, а не ecs::Entity: сущность может исчезнуть, и держать
    /// на неё ссылку между кадрами нельзя. По числу каждый кадр
    /// спрашивают заново — жива ли ещё.
    u32 id = 0;

    /// Сколько ещё показывать полосу. Обнуляется — полоса гаснет.
    f32 hold = 0.f;

    /// Доля здоровья цели на этот кадр.
    f32 fill = 0.f;

    /// След недавнего урона: вторая заливка, оседающая с задержкой.
    ///
    /// Она и отвечает на вопрос «сколько снял этот удар» — тот самый,
    /// ради которого обычно заводят всплывающие цифры. Доля понятнее
    /// абсолюта: игроку нечем мерить «47», зато «четверть полосы»
    /// он видит сразу.
    f32 ghost = 0.f;

    /// Сколько ещё след держится, прежде чем поехать вниз.
    f32 ghostDelay = 0.f;

    /// Цель погибла: полоса догорает пустой и уходит.
    bool dead = false;
};

/// Сколько полоса держится после последнего размена, сек.
constexpr f32 FOCUS_HOLD_SEC = 6.f;

/// Последняя секунда держания — затухание.
constexpr f32 FOCUS_FADE_SEC = 0.8f;

/// Сколько показывать опустевшую полосу после смерти цели.
constexpr f32 FOCUS_DEATH_SEC = 1.4f;

/// Задержка перед тем, как след поедет вниз.
constexpr f32 FOCUS_GHOST_DELAY = 0.4f;

/// Скорость оседания следа, долей полосы в секунду.
constexpr f32 FOCUS_GHOST_RATE = 0.55f;

/// Запомнить размен: игрок ударил `other` или `other` ударил игрока.
///
/// Зовётся из общей воронки урона, поэтому работает одинаково для
/// ближнего боя, стрелы, заклинания, яда и горения — и для удара,
/// пришедшего игроку.
/// `otherFill` — доля здоровья той стороны ДО этого удара. Из неё
/// начинается след: иначе первый же удар по раненой твари нарисовал
/// бы след от полной полосы и соврал бы вчетверо.
void noticeExchange(FocusTarget& f, u32 otherId, f32 otherFill);

/// Заметить урон: кто кого ударил.
///
/// Разбирается сама, участвует ли в размене игрок и с какой стороны.
/// Зовётся из общей воронки урона — поэтому одинаково работает и
/// когда бьёт игрок, и когда бьют его.
/// `targetFillBefore` — доля здоровья цели ДО этого удара.
void noticeDamage(ecs::Registry& reg, ecs::Entity target, u32 sourceId,
                  f32 targetFillBefore);

/// Продвинуть полосу на кадр: здоровье, след, держание, смерть.
void tickFocus(ecs::Registry& reg, FocusTarget& f, f32 dt);

/// Что показывать на экране.
struct FocusView {
    const char* name = "";
    /// Доля здоровья, 0..1.
    f32 fill = 0.f;
    /// След недавнего урона, 0..1. Всегда не меньше fill.
    f32 ghost = 0.f;
    /// Непрозрачность полосы, 0..1.
    f32 alpha = 0.f;
    /// Сколько у существа фаз. Единица — обычная тварь, делений нет.
    u8 phases = 1;
    /// На какой фазе оно сейчас.
    u8 phase = 0;
    bool dead = false;
};

/// Собрать то, что рисовать. false — показывать нечего.
bool focusView(ecs::Registry& reg, const FocusTarget& f, FocusView& out);

} // namespace combat
