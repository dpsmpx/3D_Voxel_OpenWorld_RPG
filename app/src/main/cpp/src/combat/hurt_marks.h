/**
 * @file hurt_marks.h
 * @brief Откуда игрока ударили: отметки по краю экрана.
 */
#pragma once
#include "../core/types.h"
#include "../ecs/registry.h"
#include <array>
#include <glm/glm.hpp>

namespace combat {

/// Одна отметка: откуда пришёл удар и сколько ей осталось.
struct HurtMark {
    /// Точка в мире, откуда ударили. Запоминается именно точка, а не
    /// сущность: бьющий успеет отойти, умереть или исчезнуть, а
    /// игроку надо знать, куда он смотрел в момент удара.
    glm::vec3 from{ 0.f };

    /// Сколько ещё показывать, в секундах.
    f32 life = 0.f;

    /// Насколько удар был силён, 0..1 от максимума здоровья. Слабый
    /// укус и удар, снёсший половину, обязаны читаться по-разному —
    /// иначе отметка отвечает только на «откуда», но не на
    /// «насколько срочно».
    f32 weight = 0.f;
};

/// Компонент игрока. Больше восьми отметок разом не бывает нужно:
/// это уже не бой, а свалка, и читать её всё равно некогда.
struct HurtMarks {
    static constexpr u32 CAPACITY = 8;
    static constexpr f32 LIFETIME = 1.6f;

    std::array<HurtMark, CAPACITY> marks{};

    /// Сколько отметок сейчас живо.
    u32 liveCount() const {
        u32 n = 0;
        for (const auto& m : marks) if (m.life > 0.f) ++n;
        return n;
    }
};

/// Запомнить удар по игроку.
///
/// Зовётся из `combat::applyDamage` — единственного пути урона в
/// игре. Если бьющего в мире уже нет (ловушка, яд, падение), отметки
/// не будет: показывать направление неоткуда, и выдумывать его
/// нельзя.
///
/// Урон без источника — не ошибка, а обычное дело: утопление, голод,
/// лава. Поэтому функция молча ничего не делает, а не жалуется.
void noticeHurt(ecs::Registry& reg, ecs::Entity player, u32 sourceId,
                f32 amount);

/// Погасить отметки за кадр.
void tickHurtMarks(HurtMarks& hm, f32 dt);

/// Куда показывает отметка относительно взгляда.
///
/// Ноль — прямо перед игроком, положительный угол — вправо, и дальше
/// по кругу до ±π. Считается от направления взгляда, а не от сторон
/// света: игрок поворачивается, и отметка обязана поворачиваться
/// вместе с ним.
f32 hurtAngle(const glm::vec3& playerPos, f32 viewYaw, const glm::vec3& from);

} // namespace combat
