/**
 * @file iso_projection.h
 * @brief Строгая ортографическая изометрия: область, камера, масштаб.
 *
 * Математика снимка и ничего больше: ни Vulkan, ни чанков, ни файлов.
 * Отсюда её можно проверить на хосте целиком, а это единственный
 * способ отвечать за проекцию числами, а не глазами.
 *
 * ============================================================
 * ОСИ МИРА
 * ============================================================
 *
 * Мир правосторонний, +Y вверх. Стороны света закреплены здесь и
 * больше нигде в проекте их не было:
 *
 *      -Z = СЕВЕР      +X = ВОСТОК
 *      +Z = ЮГ         -X = ЗАПАД
 *
 * Это согласуется с камерой игрока: `Camera::forward()` при yaw = 0
 * смотрит в +Z, то есть на юг.
 *
 * ============================================================
 * ЧЕТЫРЕ АЗИМУТА
 * ============================================================
 *
 * Вид назван по той стороне света, С КОТОРОЙ смотрят. Наблюдатель на
 * севере смотрит на юг — так «вид с севера» показывает северные грани
 * блоков, то есть ровно то, что игрок ожидает увидеть.
 *
 *      View::North  азимут   45°
 *      View::East   азимут  135°
 *      View::South  азимут  225°
 *      View::West   азимут  315°
 *
 * Азимут отсчитывается от +X к +Z (по часовой стрелке, если смотреть
 * сверху). Соседние виды отличаются ровно на 90°, и это не
 * договорённость, а следствие формулы: azimuth(v) = 45° + 90°·v.
 *
 * Сдвиг на 45° обязателен. Без него направление взгляда совпало бы с
 * осью мира, две из трёх осей слились бы на картинке в одну линию, и
 * изометрии не получилось бы.
 *
 * ============================================================
 * ВОЗВЫШЕНИЕ
 * ============================================================
 *
 * Оно ровно одно и не настраивается:
 *
 *      φ = atan(1 / √2) ≈ 35.264389°
 *
 * Это ЕДИНСТВЕННОЕ возвышение, при котором проекция даёт настоящую
 * изометрию. Признаков два, и проверяются оба:
 *
 *   1. единичные отрезки всех трёх осей мира получают на картинке
 *      ОДИНАКОВУЮ длину — отсюда и название, iso-metric, «равная
 *      мера»;
 *   2. три оси ложатся на картинку тремя ПРЯМЫМИ, попарно
 *      разнесёнными на 60°.
 *
 * Про второй признак нужна оговорка, иначе проверка ловит не то.
 * Обычно изометрию описывают как «оси под 120° друг к другу», и это
 * верно — но только для осей, направленных ОТ наблюдателя. Ось,
 * смотрящая в камеру, проецируется в противоположную сторону, и угол
 * между направлениями становится 60°. Какие именно оси смотрят в
 * камеру, зависит от стороны обзора, поэтому «120° между
 * направлениями» верно для вида с севера и неверно для вида с
 * востока. А вот 60° между ПРЯМЫМИ верно для всех четырёх, и именно
 * это — признак изометрии, не зависящий от того, откуда смотрят.
 *
 * Проверка `testIsoProjectionIsTrulyIsometric` считает ровно это.
 *
 * Любое другое возвышение (в том числе «красивое» 30°, которое берут
 * для двумерных тайлов) даёт диметрию: одна ось короче двух других.
 * Поэтому наклон здесь не вынесен в настройку — менять его нечем, не
 * разрушив геометрию.
 *
 * ============================================================
 * ПРОЕКЦИЯ
 * ============================================================
 *
 * Строго ортографическая: лучи параллельны, масштаб не зависит от
 * глубины, параллельные направления мира остаются параллельными на
 * картинке. Перспективы здесь нет ни в каком виде.
 *
 *      направление взгляда  d = (−sinθ·cosφ, −sinφ, −cosθ·cosφ)
 *      view                 = lookAt(center − d·R, center, +Y)
 *      proj                 = ortho(−hw, hw, −hh, hh, near, far)
 *
 * где θ — азимут вида, R — отступ камеры назад (любой, лишь бы вся
 * область оказалась перед ближней плоскостью: при ортографии он на
 * картинку не влияет вовсе — ещё одна проверка, что перспективы нет).
 *
 * Y в матрице проекции переворачивается, как и в игровой камере: в
 * координатах отсечения Vulkan ось Y смотрит вниз.
 *
 * ============================================================
 * МИР → ПИКСЕЛИ
 * ============================================================
 *
 * Границы hw и hh НЕ подбираются: восемь углов коробки области
 * переводятся в пространство вида, и берётся их размах. Тогда область
 * занимает кадр целиком и ровно один раз — без полей и без обрезки.
 *
 * Размер картинки в пикселях = размах в мировых единицах × масштаб
 * (пикселей на мировую единицу). Масштаб один на оба измерения,
 * поэтому блок в любом углу картинки имеет один и тот же размер.
 */
#pragma once
#include "../core/types.h"
#include <glm/glm.hpp>
#include <glm/gtc/matrix_transform.hpp>
#include <cmath>

namespace render::iso {

/// Сторона, С КОТОРОЙ смотрят. Порядок задаёт и порядок в интерфейсе.
enum class View : u8 { North = 0, East = 1, South = 2, West = 3, Count = 4 };

/// Возвышение камеры. Ровно atan(1/√2) — см. шапку файла.
inline f32 elevationRad() { return std::atan(1.f / std::sqrt(2.f)); }

/// Азимут вида, радианы. 45° + 90°·v, без исключений.
inline f32 azimuthRad(View v) {
    return glm::radians(45.f + 90.f * (f32)(u32)v);
}

/// Единичное направление ВЗГЛЯДА (от камеры к области).
inline glm::vec3 viewDirection(View v) {
    const f32 th = azimuthRad(v), ph = elevationRad();
    const f32 cp = std::cos(ph);
    return { -std::sin(th) * cp, -std::sin(ph), -std::cos(th) * cp };
}

/// Квадрат мира в блоках: [x0, x0+size) × [z0, z0+size).
struct Area {
    i32 x0 = 0, z0 = 0;
    i32 size = 100;

    i32 x1() const { return x0 + size; }
    i32 z1() const { return z0 + size; }
    /// Геометрический центр области в мировых координатах.
    glm::vec2 centerXZ() const {
        return { (f32)x0 + (f32)size * 0.5f, (f32)z0 + (f32)size * 0.5f };
    }
};

/// Область вокруг точки.
///
/// ПРАВИЛО ОКРУГЛЕНИЯ, зафиксированное здесь раз и навсегда: центром
/// считается БЛОК, в котором стоит игрок, то есть floor(позиции).
/// Область строится так, чтобы этот блок оказался в середине.
///
/// При нечётном размере середина одна, и блок игрока — ровно она.
/// При чётном середины нет: блок игрока берётся левым из двух
/// центральных (x0 = cx - size/2). Иначе пришлось бы выбирать
/// «примерно посередине», а два снимка с соседних углов блока давали
/// бы разные области — при том что игрок не сходил с места.
///
/// Дробная часть позиции в результат не входит НИКАК: снимок из
/// любой точки одного блока даёт один и тот же кадр.
inline Area areaAround(const glm::vec3& pos, i32 size) {
    if (size < 1) size = 1;
    const i32 cx = (i32)std::floor(pos.x);
    const i32 cz = (i32)std::floor(pos.z);
    return { cx - size / 2, cz - size / 2, size };
}

/// Диапазон чанков, накрывающих область.
///
/// Вынесено из подготовки снимка сюда, потому что это арифметика, а
/// не графика: её можно (и нужно) проверить на хосте. Границы
/// ВКЛЮЧИТЕЛЬНЫЕ.
///
/// Деление здесь целочисленное со сдвигом вниз, а не `size / 32`:
/// у отрицательных координат обычное деление округляет к нулю, и
/// блок -1 попал бы в чанк 0 вместо -1.
struct ChunkRange {
    i32 x0, x1, z0, z1;
    i32 countX() const { return x1 - x0 + 1; }
    i32 countZ() const { return z1 - z0 + 1; }
    i32 count()  const { return countX() * countZ(); }
};

inline ChunkRange chunkRange(const Area& a, i32 chunkSize, i32 border = 0) {
    auto down = [chunkSize](i32 v) {
        return (v >= 0) ? (v / chunkSize)
                        : -(((-v) + chunkSize - 1) / chunkSize);
    };
    return { down(a.x0) - border, down(a.x1() - 1) + border,
             down(a.z0) - border, down(a.z1() - 1) + border };
}

/// Готовая камера снимка: матрицы и размер картинки.
struct Camera {
    glm::mat4 view{1.f};
    glm::mat4 proj{1.f};
    /// Размах области в пространстве вида, мировые единицы.
    f32 spanX = 0.f, spanY = 0.f;
    /// Пиксели на одну мировую единицу — один на оба измерения.
    f32 pixelsPerUnit = 0.f;
    u32 width = 0, height = 0;

    glm::mat4 viewProj() const { return proj * view; }
};

/// Коробка области: квадрат по X/Z и заданный диапазон высот.
struct Box {
    Area area;
    f32  yMin = 0.f;
    f32  yMax = 128.f;

    glm::vec3 center() const {
        const glm::vec2 c = area.centerXZ();
        return { c.x, (yMin + yMax) * 0.5f, c.y };
    }
    /// Восемь углов. Порядок неважен — берётся только размах.
    void corners(glm::vec3 out[8]) const {
        const f32 xs[2] = { (f32)area.x0, (f32)area.x1() };
        const f32 zs[2] = { (f32)area.z0, (f32)area.z1() };
        const f32 ys[2] = { yMin, yMax };
        u32 n = 0;
        for (f32 x : xs) for (f32 y : ys) for (f32 z : zs)
            out[n++] = { x, y, z };
    }
};

/// Матрица вида для коробки и стороны обзора.
///
/// Камера отводится назад настолько, чтобы коробка целиком оказалась
/// перед ближней плоскостью. При ортографии отступ на картинку не
/// влияет — он нужен только чтобы ничего не обрезалось по глубине.
inline glm::mat4 makeView(const Box& box, View v, f32 backOff) {
    const glm::vec3 c = box.center();
    const glm::vec3 d = viewDirection(v);
    return glm::lookAt(c - d * backOff, c, glm::vec3(0.f, 1.f, 0.f));
}

/// Полная камера снимка.
///
/// @param pixelsPerUnit  сколько пикселей приходится на одну мировую
///                       единицу; отсюда и разрешение картинки.
/// @param maxSide        потолок на сторону картинки; при его
///                       превышении масштаб уменьшается, а не
///                       обрезается область.
Camera makeCamera(const Box& box, View v, f32 pixelsPerUnit, u32 maxSide);

/// Куда попадёт мировая точка на картинке, в пикселях.
/// Левый верхний угол картинки — (0, 0).
glm::vec2 worldToImage(const Camera& cam, const glm::vec3& world);

} // namespace render::iso
