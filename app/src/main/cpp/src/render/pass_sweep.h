namespace render {

/// Развёртка по проходам: сколько стоит каждый проход кадра.
///
/// Зачем не метки времени внутри прохода. Мобильный GPU плиточный: он
/// раскладывает геометрию всего прохода рендера по плиткам и красит их
/// потом, все проходы вперемешку. Метка посреди прохода дожидается
/// всей отложенной работы разом — на устройстве весь кадр собирался в
/// ПЕРВОЙ метке (ландшафт 12.93 мс), остальные шесть показывали ноль.
/// И стоила эта попытка двух миллисекунд из одиннадцати: та же сцена
/// шла 10.8..11.3 мс без меток и 12.7..13.3 мс с ними.
///
/// Что работает вместо них. Выключить проход целиком и посмотреть на
/// ПОЛНОЕ время кадра — его метки стоят вокруг командного буфера, и
/// тайлеру там нечего откладывать. Разность с опорным замером и есть
/// цена прохода.
///
/// Почему это делается само, а не руками. Руками — семь запусков с
/// правкой render_passes между ними, а settings.cfg на свежем
/// устройстве появляется только ПОСЛЕ первого выхода: первый запуск
/// править нечего. Диагностическая сборка для замеров и существует,
/// сцена в ней постоянная и камера прибита — одного запуска хватает
/// на всю таблицу.
class PassSweep {
public:
    /// Сколько секунд держать одну комбинацию и сколько из них
    /// выбросить на разгон. Первые кадры после смены маски идут по
    /// другим конвейерам и в среднее не годятся.
    static constexpr f32 STEP_SEC = 4.f;
    static constexpr f32 WARMUP_SEC = 1.f;

    struct Step {
        u32         mask;
        const char* name;   ///< что выключено
        const char* what;   ///< чью цену даёт разность с опорным
    };

    /// Опорный замер идёт первым: разность считается от него.
    static constexpr Step STEPS[] = {
        { 0x7F, "всё включено",   ""          },
        { 0x77, "без неба",       "небо"      },
        { 0x3F, "без интерфейса", "интерфейс" },
        { 0x7E, "без ландшафта",  "ландшафт"  },
        { 0x7B, "без травы",      "трава"     },
        { 0x6F, "без воды",       "вода"      },
        { 0x7D, "без существ",    "существа"  },
    };
    static constexpr u32 STEP_COUNT = (u32)(sizeof(STEPS) / sizeof(STEPS[0]));

    void start() { active_ = true; step_ = 0; elapsed_ = 0.f; reset(); }
    void stop()  { active_ = false; }
    bool active() const { return active_; }

    /// Маска, которую надо поставить этому кадру.
    u32 mask() const { return active_ ? STEPS[step_].mask : 0x7Fu; }

    /// Кадр прошёл. gpuMs — полное время кадра по меткам GPU.
    /// Возвращает true, когда круг замкнулся и таблица готова.
    bool tick(f32 dt, f32 gpuMs);

    /// Печатает таблицу в журнал. Зовётся после tick() == true.
    void report() const;

private:
    void reset() { sumMs_ = 0.0; frames_ = 0; }

    bool active_  = false;
    u32  step_    = 0;
    f32  elapsed_ = 0.f;
    f64  sumMs_   = 0.0;
    u32  frames_  = 0;
    f32  result_[STEP_COUNT] = {};
    u32  counted_[STEP_COUNT] = {};
    u32  done_    = 0;    ///< сколько шагов уже замерено
};

} // namespace render
