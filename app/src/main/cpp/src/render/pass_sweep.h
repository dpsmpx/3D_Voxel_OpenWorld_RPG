namespace render {

/// Развёртка по проходам: сколько стоит каждый проход кадра.
///
/// Зачем не метки времени внутри прохода. Мобильный GPU плиточный: он
/// раскладывает геометрию всего прохода рендера по плиткам и красит их
/// потом, все проходы вперемешку. Метка посреди прохода дожидается
/// всей отложенной работы разом — на устройстве весь кадр собирался в
/// ПЕРВОЙ метке (ландшафт 12.93 мс), остальные шесть показывали ноль.
/// И стоила эта попытка двух миллисекунд из одиннадцати.
///
/// Что работает вместо них. Выключить проход целиком и посмотреть на
/// ПОЛНОЕ время кадра. Разность с опорным замером и есть цена прохода.
///
/// ---- Две поправки, без которых первая версия врала ----
///
/// **Пустой кадр.** Первый замер дал сумму всех проходов 1.5 мс из
/// 10.8, то есть девять миллисекунд ни на что. Чтобы понять, рисование
/// это вообще или нет, нужен нижний предел: кадр, в котором не
/// нарисовано НИЧЕГО. Что останется — это проход рендера, очистка,
/// показ и ожидание картинки цепочки, а не работа шейдеров.
///
/// **Чередование.** Первая версия отводила каждой комбинации один
/// отрезок подряд, и два круга подряд дали по одному и тому же проходу
/// 0.56 и 1.36 мс. Такой разброс — не выборочный шум на трёх сотнях
/// кадров, а медленный уход: телефон греется и меняет частоты.
/// Комбинации теперь чередуются короткими отрезками и набирают своё
/// время по многу раз, вперемешку, — уход при этом размазывается по
/// всем поровну вместо того, чтобы целиком достаться одной.
class PassSweep {
public:
    /// Отрезок на одну комбинацию и сколько из него выбросить на
    /// разгон: первые кадры после смены маски идут по другим
    /// конвейерам и в среднее не годятся.
    static constexpr f32 SLICE_SEC  = 0.80f;
    static constexpr f32 WARMUP_SEC = 0.30f;
    /// Сколько раз пройти весь набор. Семь кругов по одиннадцать
    /// комбинаций — около минуты на весь замер.
    static constexpr u32 ROUNDS = 7;

    struct Step {
        u32         mask;
        /// Отладочный вид террейна на этой ступени, 0 — обычная
        /// картинка. Вид 1 — ранний выход из фрагментного шейдера
        /// сразу после распаковки: цвет вершины и больше ничего.
        /// Разность с обычным видом и есть цена всей математики
        /// фрагмента — освещения, фаски, тумана, перевода в линейное
        /// пространство и обратно.
        u8          shading;
        /// Порядок непрозрачных чанков на этой ступени: 0 — от
        /// ближнего к дальнему (как в игре), 1 — наоборот. Картинку
        /// это не меняет, время меняет ровно на то, сколько экономит
        /// ранний тест глубины.
        u8          farFirst;
        const char* name;
        /// Что добавляет этот шаг к ПРЕДЫДУЩЕМУ в накопительной части
        /// таблицы. Пусто — шаг не накопительный.
        const char* adds;
    };

    /// Набор устроен в три яруса, и это не украшение.
    ///
    /// Первый замер выключал проходы по одному. На устройстве это дало
    /// сумму 1.76 мс при том, что выключение ВСЕГО разом снимает
    /// 10.06 мс. Расхождение в восемь миллисекунд — не шум, а изъян
    /// самого способа: проходы ПОДМЕНЯЮТ друг друга на экране. Небо
    /// рисуется последним и с проверкой глубины, поэтому оно
    /// закрашивает ровно то, что не закрыл ландшафт. Убери ландшафт —
    /// его две трети экрана достанутся небу, и кадр не подешевеет.
    /// Цена ландшафта при этом не ноль, просто её нечем увидеть.
    ///
    /// Поэтому главный ярус — НАКОПИТЕЛЬНЫЙ: от пустого кадра вверх,
    /// добавляя по одному проходу. Разность соседних строк — это то,
    /// что добавил очередной проход при уже нарисованном предыдущем, и
    /// подменять здесь некому.
    ///
    /// Второй ярус, выключение по одному, оставлен для сравнения:
    /// именно расхождение между ярусами и показывает, сколько работы
    /// перетекает между проходами.
    ///
    /// Третий ярус — проход В ОДИНОЧКУ поверх пустого кадра. Он нужен,
    /// когда накопительная разность начинает вести себя странно: она
    /// верна, пока проходы складываются, а если нет — переложит
    /// стоимость на соседа и не скажет об этом.
    static constexpr Step STEPS[] = {
        // опорное и пол
        { 0x7F, 0, 0, "всё включено",        ""            },
        { 0x00, 0, 0, "пустой кадр",         ""            },
        // Накопительно снизу вверх. Ландшафт разбит надвое: сперва он
        // же с ранним выходом из фрагментного шейдера (растеризация,
        // вершины, запись цвета), потом он же целиком. Разность —
        // цена математики фрагмента, и её нельзя получить иначе:
        // выключить «освещение, но не рисование» нечем.
        { 0x01, 1, 0, "ландшафт без света",  "растеризация ландшафта" },
        { 0x01, 0, 0, "ландшафт целиком",    "математика фрагмента"   },
        { 0x09, 0, 0, "и небо",              "небо"        },
        { 0x49, 0, 0, "и интерфейс",         "интерфейс"   },
        { 0x7F, 0, 0, "и всё остальное",     "трава, вода, существа" },
        // для сравнения — выключение по одному
        { 0x7E, 0, 0, "без ландшафта",       ""            },
        // Третий ярус: проход ОДИН, поверх пустого кадра.
        //
        // Накопительный ярус даёт цену прохода разностью соседних
        // строк, и это верно, пока проходы складываются. Замер
        // 11.14 -> 9.89 показал, что не всегда: ландшафт подешевел на
        // 2.09 мс, а приписанная небу разность выросла на 1.08 — при
        // том, что sky.frag стал меньше и делает на одно умножение
        // меньше. Дорожать ему было не с чего, значит разность
        // переложила часть стоимости на соседа.
        //
        // Небо в одиночку от разности не зависит: перед ним пустой
        // кадр, закрывать его пикселям нечем, и его цена — это просто
        // «сколько стало» минус «пустой кадр».
        { 0x08, 0, 0, "только небо",         ""            },
        // Четвёртый ярус: тот же ландшафт, но нарисованный от ДАЛЬНЕГО
        // к ближнему.
        //
        // Картинка при этом не меняется: геометрия непрозрачная, тест
        // глубины включён, порядок на результат не влияет. Меняется
        // только одно — ранний тест глубины перестаёт отбрасывать
        // закрытые фрагменты, потому что ближнее рисуется последним.
        //
        // Разница с обычным порядком и есть то, сколько ранний тест
        // экономит СЕЙЧАС. Если она мала, значит перекрытия почти нет
        // и сортировка ни от чего не спасает; если велика — перекрытие
        // есть, и вопрос в том, нельзя ли отсечь его раньше.
        //
        // Пары задаются порядком: ORDER_FIRST сравнивается с
        // CUMUL_FIRST, следующая — со следующей.
        { 0x01, 1, 1, "растеризация, дальние первыми", "" },
        { 0x01, 0, 1, "ландшафт целиком, дальние первыми", "" },
    };
    /// Границы накопительного яруса в STEPS.
    static constexpr u32 CUMUL_FIRST = 2;
    static constexpr u32 CUMUL_LAST  = 6;
    /// Начало яруса «проход в одиночку»; между ним и CUMUL_LAST —
    /// ярус «выключением по одному».
    static constexpr u32 SOLO_FIRST  = 8;
    /// Начало яруса «тот же ландшафт, но дальние первыми». Каждая его
    /// ступень сравнивается со ступенью накопительного яруса на том же
    /// месте: ORDER_FIRST с CUMUL_FIRST, ORDER_FIRST+1 с CUMUL_FIRST+1.
    static constexpr u32 ORDER_FIRST = 9;
    static constexpr u32 STEP_COUNT = (u32)(sizeof(STEPS) / sizeof(STEPS[0]));

    void start();
    void stop() { active_ = false; }
    bool active() const   { return active_; }
    /// Весь набор пройден нужное число раз, таблица напечатана.
    bool finished() const { return finished_; }

    /// Маска, которую надо поставить этому кадру.
    u32 mask() const { return active_ ? STEPS[step_].mask : 0x7Fu; }
    /// Отладочный вид террейна для этого кадра, 0 — обычная картинка.
    u8  shading() const { return active_ ? STEPS[step_].shading : (u8)0; }
    /// Рисовать ли непрозрачные чанки от дальнего к ближнему. Только
    /// для замера: в игре всегда от ближнего.
    bool farFirst() const { return active_ && STEPS[step_].farFirst != 0; }

    /// Кадр прошёл. gpuMs — полное время кадра по меткам GPU.
    /// Возвращает true, когда замер закончен и таблица готова.
    bool tick(f32 dt, f32 gpuMs);

    /// Печатает таблицу в журнал. Зовётся после tick() == true.
    void report() const;

private:
    bool active_   = false;
    bool finished_ = false;
    u32  step_     = 0;
    u32  round_    = 0;
    f32  elapsed_  = 0.f;
    f64  sum_[STEP_COUNT]    = {};
    u32  frames_[STEP_COUNT] = {};
};

} // namespace render
