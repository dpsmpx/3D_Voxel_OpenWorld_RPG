/**
 * @file flora_models.h
 * @brief Рендер: модели растений и мелких природных вещей из мелких вокселей.
 *
 * Земля собрана из блоков, а растения — из вокселей в четыре-восемь
 * раз мельче: дерево — воксель в четверть блока, трава и камешки — в
 * восьмую. Модель одна на (вид, вариант) и общая для всех экземпляров;
 * разнообразие дают поворот, размер и оттенок экземпляра.
 *
 * Модель описана не сеткой, а формами в блоках — ствол, крона,
 * ветви, травинки, — и сетка строится по описанию для каждой ступени
 * детальности. Прореживание готовой сетки теряло бы тонкое: ствол в
 * полблока на ступени «воксель — блок» либо пропадал, либо толстел
 * вдвое. Из описания он остаётся стволом на любой ступени.
 */
#pragma once
#include "../core/types.h"
#include "../world/flora_types.h"
#include "voxel_model.h"
#include <vector>

namespace render {

/// Ступени детальности: воксель своего размера, вдвое, вчетверо и
/// вовосьмеро крупнее. Ближние растения — первая, лес у горизонта —
/// последняя (её видят только деревья: мелочь так далеко не рисуется).
constexpr u32 FLORA_LODS = 4;

/// Номер модели (вид, вариант) в общей таблице. Вариант берётся по
/// модулю числа вариантов вида.
u32 floraModelIndex(world::FloraKind k, u8 variant);
/// Сколько всего моделей (без учёта ступеней).
u32 floraModelCount();

/// Размер вокселя вида на первой ступени, в блоках.
f32 floraVoxelSize(world::FloraKind k);

/// Модель растения на ступени lod, стоит на Y = 0, ствол — на оси.
VoxelModel buildFloraModel(world::FloraKind k, u8 variant, u32 lod);

/// Все меши: индекс floraModelIndex(k, v) * FLORA_LODS + lod.
std::vector<VoxelMesh> buildFloraMeshes();

/// Насколько растение гнётся на ветру, 0..1: трава — вся, куст —
/// немного, дерево — едва, камень — никак.
f32 floraSway(world::FloraKind k);

/// Габарит модели в её собственных единицах (до размера экземпляра):
/// высота над основанием и радиус от оси, покрывающий любой поворот.
struct FloraExtent { f32 height = 0.f; f32 radius = 0.f; };

/// Габарит первой ступени каждой модели — по мешам из buildFloraMeshes,
/// индекс — floraModelIndex. Первая ступень самая подробная, и её
/// коробка не меньше коробки любой другой.
std::vector<FloraExtent> floraExtents(const std::vector<VoxelMesh>& meshes);

} // namespace render
