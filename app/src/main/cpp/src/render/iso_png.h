/**
 * @file iso_png.h
 * @brief Запись PNG. Тонкая надстройка над уже линкуемым zlib.
 *
 * Своя запись, а не библиотека, по двум причинам. Первая: всё, что
 * нужно PNG, в проекте уже есть — zlib для IDAT и его же crc32 для
 * контрольных сумм каждого блока (`save::zcompress`,
 * `save::crc32_compute`). Вторая: единственный формат, который нам
 * нужен, — восемь бит на канал, три канала, без чересстрочности; это
 * сотня строк, а не зависимость.
 *
 * Формат: signature, IHDR, IDAT, IEND. Ровно по спецификации, потому
 * что открывать файл будет не игра, а галерея телефона и любой
 * просмотрщик на другом конце.
 */
#pragma once
#include "../core/types.h"
#include <vector>

namespace render {

/// Кодирует RGB8 в PNG.
///
/// @param rgb     w*h*3 байта, построчно сверху вниз.
/// @return        готовый файл; пустой вектор — ошибка.
std::vector<u8> encodePng(const u8* rgb, u32 w, u32 h);

/// Пишет PNG на диск. Возвращает false, если не удалось.
///
/// Через временный файл и переименование: превью мира пишется при
/// закрытии приложения, и система вправе убить процесс посреди
/// записи — оборванный файл не должен занять место целого.
bool writePngFile(const char* path, const u8* rgb, u32 w, u32 h);

/// Читает PNG, который пишет encodePng: восемь бит на канал, RGB или
/// RGBA (альфа отбрасывается), без чересстрочности, любой из пяти
/// фильтров строки.
///
/// Нужно превью миров: они лежат на диске теми же PNG, что и
/// снимки, — их открывает и галерея, — а показать их игра может
/// только разжав обратно. Чужие PNG с палитрой, серые и 16-битные
/// честно отвергаются: их игра не пишет.
///
/// @return false — не PNG, не тот формат или файл повреждён.
bool decodePng(const std::vector<u8>& png, std::vector<u8>& rgb,
               u32& w, u32& h);

/// То же с диска.
bool readPngFile(const char* path, std::vector<u8>& rgb, u32& w, u32& h);

} // namespace render
