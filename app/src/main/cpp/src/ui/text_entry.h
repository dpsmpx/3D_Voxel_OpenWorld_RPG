/**
 * @file text_entry.h
 * @brief Интерфейс: ввод текста с экранной клавиатуры.
 */
#pragma once
#include "../core/types.h"
#include "ui_types.h"

namespace ui {

/// Страница экранной клавиатуры.
///
/// Три, а не одна: все буквы обеих азбук вместе с цифрами не влезают
/// на экран телефона клавишами, по которым можно попасть пальцем.
enum class KeyPage : u8 {
    Latin = 0,
    Cyrillic,
    Digits,
    Count
};

/// Поле ввода: буфер и правила, по которым он меняется.
///
/// Модель отдельно от рисования намеренно. Нарисованную клавиатуру
/// проверить нечем, а «что окажется в буфере после этих нажатий» —
/// можно, и ломается как раз это: обрезанная посреди буквы строка,
/// переполнение, забой на пустом поле.
class TextEntry {
public:
    /// Сколько байт помещается. Ровно столько же, сколько в
    /// save::SlotMeta::worldName: имя, которое не сохранится целиком,
    /// незачем и набирать.
    static constexpr u32 CAP = 31;

    void clear() { buf_[0] = '\0'; len_ = 0; }

    /// Дописать символ. false — не влезло или рисовать его нечем.
    ///
    /// Кириллица в UTF-8 двухбайтовая, и «влезло» считается в
    /// БАЙТАХ: буква, влезшая наполовину, превращает строку в мусор
    /// с середины.
    bool insert(u32 codepoint);

    /// Стереть последний СИМВОЛ, а не байт. false — поле пусто.
    bool backspace();

    /// Заменить содержимое. Всё, что не влезло или не рисуется,
    /// отбрасывается — на вход эта строка приходит из файла.
    void setText(const char* s);

    const char* text()  const { return buf_; }
    u32         bytes() const { return len_; }
    bool        empty() const { return len_ == 0; }

    /// Символов, а не байтов: по ним считается курсор.
    u32 glyphs() const;

private:
    char buf_[CAP + 1] = {};
    u32  len_ = 0;
};

/// Рядов клавиш на странице.
u32 keyRowCount(KeyPage p);

/// Ряд клавиш — строка UTF-8, по символу на клавишу.
/// Пустая строка, если ряда нет.
const char* keyRow(KeyPage p, u32 row);

/// Подпись кнопки переключения на эту страницу.
const char* keyPageName(KeyPage p);

/// Следующая страница по кругу.
inline KeyPage nextKeyPage(KeyPage p) {
    return (KeyPage)(((u8)p + 1) % (u8)KeyPage::Count);
}

/// Сколько клавиш в ряду. Считает СИМВОЛЫ: кириллица в UTF-8
/// двухбайтовая, и по байтам ряд вышел бы вдвое длиннее, чем на вид.
u32 keysInRow(KeyPage p, u32 row);

/// Символ клавиши. 0 — такой клавиши нет.
u32 keyAt(KeyPage p, u32 row, u32 col);

/// Геометрия экранной клавиатуры.
///
/// Считается здесь, а не при рисовании. Проверке нужна ровно та же
/// раскладка, по которой экран ловит касания; копия её правил
/// проверяла бы копию, а расходятся они молча — нажатие попадает
/// мимо клавиши, и ввода просто нет.
struct KeyboardLayout {
    Rect area{0.f, 0.f, 0.f, 0.f};
    KeyPage page = KeyPage::Latin;
    f32 keyH = 0.f;
    f32 gap  = 0.f;

    /// Клавиша буквенного ряда.
    Rect keyRect(u32 row, u32 col) const;

    /// Служебный ряд: страница, пробел, забой.
    Rect pageRect() const;
    Rect spaceRect() const;
    Rect backspaceRect() const;
};

/// Разложить клавиатуру по области. minKeyH — цель касания: клавиша
/// мельче неё бесполезна, лучше вылезти за область.
KeyboardLayout keyboardLayout(KeyPage p, Rect area, f32 gap, f32 minKeyH);

} // namespace ui
