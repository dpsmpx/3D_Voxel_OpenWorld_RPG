/**
 * @file preview_atlas.h
 * @brief Атлас превью миров: несколько снимков — одна текстура.
 *
 * Превью мира — изометрический снимок области вокруг игрока, снятый
 * тем же render::IsoSnapshot, что и снимок из настроек, в момент
 * выгрузки мира (см. main.cpp, renderWorldPreview). На экране миров
 * их до девяти сразу, а у интерфейса одно гнездо картинки на экран
 * (ui::ImageSlot): отдельная текстура на мир — это девять наборов
 * дескрипторов и девять отрезков рисования ради девяти карточек.
 *
 * Поэтому снимки складываются в один атлас сеткой ячеек. Снимок
 * вписывается в ячейку с сохранением пропорций — растянутая
 * изометрия уже не изометрия — и только уменьшается: мелкий снимок
 * встаёт по центру как есть. Ячейки разделены полем: линейная
 * выборка на краю одной картинки иначе цепляла бы соседнюю.
 *
 * Здесь только арифметика на процессоре — без Vulkan: так атлас
 * проверяется на хосте (tools/hostcheck), а текстуру из него делает
 * тот, у кого есть устройство.
 */
#pragma once
#include "../core/types.h"
#include <vector>

namespace ui {

/// Снимок для атласа: RGB8 построчно сверху вниз. Пустой — ячейка
/// остаётся фоном, и has у неё false.
struct PreviewImage {
    const u8* rgb = nullptr;
    u32 w = 0, h = 0;
};

/// Где в атласе лежит картинка ячейки.
struct PreviewCell {
    bool has = false;
    /// Текстурные координаты картинки без поля — края отступают на
    /// полпикселя внутрь, чтобы выборка не заходила за картинку.
    f32 u0 = 0.f, v0 = 0.f, u1 = 0.f, v1 = 0.f;
    /// Ширина к высоте вписанной картинки: карточка подгоняет по ней
    /// своё окно.
    f32 aspect = 1.f;
    /// Размер картинки в атласе, пиксели.
    u32 w = 0, h = 0;
};

struct PreviewAtlas {
    /// Ячейка атласа. Снимок области 64x64 при четырёх пикселях на
    /// блок выходит около 360 точек в ширину — ячейки хватает с
    /// запасом, а на экране карточка всё равно меньше.
    static constexpr u32 CELL_W = 384;
    static constexpr u32 CELL_H = 288;
    /// Поле между ячейками.
    static constexpr u32 GUTTER = 2;
    /// Фон: цвет, которым снимок заливает пустоту вокруг ромба
    /// (render/iso_snapshot.cpp, clears[0]). Поле того же цвета, и
    /// шов между картинкой и полем не виден.
    static constexpr u8 BG_R = 15, BG_G = 18, BG_B = 23;

    u32 width = 0, height = 0;
    u32 cols = 0, rows = 0;
    std::vector<u8> rgba;             ///< width*height*4
    std::vector<PreviewCell> cells;   ///< по одной на входной снимок
};

/// Сложить снимки в атлас по `cols` в ряд.
///
/// Ни одного снимка нет — атлас пуст (width == 0): текстуру из него
/// делать незачем.
PreviewAtlas buildPreviewAtlas(const std::vector<PreviewImage>& images, u32 cols);

} // namespace ui
