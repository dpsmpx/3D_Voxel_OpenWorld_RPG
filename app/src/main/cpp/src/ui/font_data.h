/// Всего клеток в атласе шрифта.
static constexpr int GLYPH_COUNT = FONT_COUNT + CYR_COUNT;

/// Номер клетки по коду символа Юникода. -1 — рисовать нечем.
///
/// Строчные приводятся к заглавным: шрифт заглавный целиком, и
/// отдельный набор строчных в 5x7 всё равно неразличим.
inline int glyphIndex(u32 cp) {
    if (cp >= 'a' && cp <= 'z') cp = cp - 'a' + 'A';
    if ((int)cp >= FONT_FIRST && (int)cp <= FONT_LAST)
        return (int)cp - FONT_FIRST;

    if (cp >= 0x430 && cp <= 0x44F) cp -= 0x20;   // строчные а-я
    if (cp == 0x451) cp = 0x401;                  // ё
    if (cp >= 0x410 && cp <= 0x42F)
        return FONT_COUNT + (int)(cp - 0x410);
    if (cp == 0x401) return FONT_COUNT + 32;      // Ё в конце
    if (cp == 0x2014 || cp == 0x2013)             // — и –
        return FONT_COUNT + 33;

    return -1;
}

/// Разбор UTF-8. Возвращает код символа и сдвигает позицию.
///
/// Кириллица в UTF-8 двухбайтовая (0xD0/0xD1 + продолжение). Пока
/// строка читалась побайтно, каждая буква давала два пробела.
inline u32 utf8Next(const char* s, usize len, usize& i) {
    const u8 b0 = (u8)s[i];
    if (b0 < 0x80) { ++i; return b0; }
    if ((b0 & 0xE0) == 0xC0 && i + 1 < len) {
        const u32 cp = ((u32)(b0 & 0x1F) << 6) | (u32)((u8)s[i + 1] & 0x3F);
        i += 2;
        return cp;
    }
    if ((b0 & 0xF0) == 0xE0 && i + 2 < len) {
        const u32 cp = ((u32)(b0 & 0x0F) << 12) |
                       ((u32)((u8)s[i + 1] & 0x3F) << 6) |
                       (u32)((u8)s[i + 2] & 0x3F);
        i += 3;
        return cp;
    }
    ++i;                 // битый байт — пропускаем
    return (u32)' ';
}

