struct AIAgent {
    enum State : u8 { Idle, Patrol, Chase, Attack, Flee, Dead } state = Idle;
    Entity target{};
    glm::vec3 homePos{0};
    f32 stateTime = 0.f;
    f32 attackRange = 2.f;
    f32 aggroRange  = 12.f;
    f32 moveSpeed   = 3.f;
    f32 attackCooldown = 0.f;
};

/// — Коллайдер (для физики)
/// Куда игрок возвращается после смерти.
///
/// Точка, а не координаты мира «как есть»: её ставит касание
/// колодца, и без отметки «поставлена» первый же респаун унёс бы в
/// нулевые координаты, то есть под землю на краю мира.
