/// Куда сущность смотрит и куда движется.
///
/// Раньше этого не существовало: рендер каждый кадр вычислял угол
/// заново из мгновенной скорости в локальную переменную, а при
/// скорости ниже порога обнулял её. Отсюда две беды. Во-первых,
/// поворот скачком: при старте мгновенный доворот, при остановке
/// мгновенный разворот на север. Во-вторых, хранить промежуточное
/// состояние плавного доворота было негде, так что плавности не
/// могло быть в принципе.
///
/// Теперь это состояние сущности. Рендер его ЧИТАЕТ и не вычисляет.
struct Facing {
    /// Куда смотрит модель. Единственное, что берёт рендер.
    f32 yaw = 0.f;
    /// Куда сущность движется. Обновляется, только когда скорость
    /// значима; при остановке сохраняет прежнее значение.
    f32 moveYaw = 0.f;
    /// Насколько быстро модель доворачивается, рад/с.
    f32 turnRate = 8.f;
};

/// Фаза шага — считается ПУТЁМ, а не временем.
///
/// Раньше её двигали строчки вида `walkPhase += dt * 9.f`,
/// разбросанные по состояниям ИИ: в покое 2, в ходьбе 6, в погоне 9.
/// Скорость и длина шага при этом не были связаны ничем, поэтому ноги
/// скользили по земле — и подобрать «правильный» множитель было
/// нельзя в принципе: он верен ровно для одной скорости.
///
/// Здесь фаза продвигается пройденным путём, делённым на длину шага.
/// Согласованность скорости и шага становится следствием формулы, а
/// не настройкой.
struct Gait {
    /// Фаза шага, радианы. При остановке ЗАМИРАЕТ, а не сбрасывается:
    /// иначе существо дёргает ногой всякий раз, как встанет.
    f32 phase = 0.f;
    /// Путь за полный цикл шага, метры. Берётся из оснастки модели:
    /// у курицы и у коровы он разный, и это свойство модели, а не
    /// состояния.
    f32 stride = 1.6f;
};

/// Семя внешности особи.
///
/// Раньше все селяне деревни были побайтово одинаковы: оснастка
/// строилась одна на вид, и шесть жителей отличались друг от друга
/// только координатами. Деревня выглядела складом одинаковых кукол.
///
/// Семя берётся из ПОСТОЯННОГО ключа NPC, а не из номера сущности:
/// иначе селянин менял бы рост и цвет рубахи всякий раз, как чанк
/// выгружался и загружался обратно.
struct Appearance {
    u32 seed = 0;
};

/// Состояние передвижения: покой, шаг, бег, прыжок, падение, приземление.
///
/// Выбирается по ФАКТИЧЕСКОЙ скорости и признаку опоры, а не по
/// состоянию ИИ. Состояние ИИ — это намерение («преследую»), а поза
/// зависит от того, что происходит: преследовать можно и в падении.
///
/// Переходы не мгновенные. Прежняя анимация знала ровно два положения
/// — покой и шаг — и смешивала их по скорости; прыжка, падения и
/// приземления не было вовсе, и существо падало с обрыва, перебирая
/// ногами по воздуху.
struct Locomotion {
    enum class State : u8 { Idle, Walk, Run, Jump, Fall, Land };

    State state     = State::Idle;
    f32   stateTime = 0.f;   ///< сколько уже в этом состоянии, секунды

    /// Доли воздушной и посадочной поз, 0..1. Нарастают и гаснут
    /// плавно — это и есть переход. Хранить предыдущую позу целиком
    /// было бы вчетверо дороже и ничего бы не добавило.
    f32 air  = 0.f;
    f32 land = 0.f;

    /// Куда идёт движение по вертикали: +1 вверх, -1 вниз, 0 на земле.
    /// Взлетая, ноги поджимаются; падая — вытягиваются навстречу
    /// земле. Это разные позы, и одной долей `air` их не различить.
    f32 rise = 0.f;

    /// Есть ли опора. Пишет тот, кто двигает сущность: контроллер
    /// игрока, ИИ моба. У того, кто земли не покидает, остаётся true.
    bool grounded = true;
};

struct Health {
    f32 current = 100.f;
    f32 max     = 100.f;
    f32 regen   = 1.f;    // hp/sec
    f32 invulnTime = 0.f;
    /// Сколько секунд прошло с последнего урона. Здоровье отрастает
    /// только в покое (progression::HEALTH_REGEN_DELAY): раньше оно
    /// шло и посреди драки, и волк, кусавший на две с половиной в
    /// секунду, против отрастающих полутора убивал игрока минуту.
    f32 sinceHurt = 1e6f;
};

struct Mana {
    f32 current = 50.f;
    f32 max     = 50.f;
    f32 regen   = 2.f;
};

struct Stamina {
    f32 current = 100.f;
    f32 max     = 100.f;
    f32 regen   = 10.f;
};

/// Дыхание под водой.
///
/// Без него погружение ничем не ограничено: можно уйти на дно и
/// жить там. Запас воздуха и делает ныряние решением — докуда
/// хватит, а не «доплыву когда-нибудь».
struct Breath {
    f32 current = 20.f;
    f32 max     = 20.f;
    /// Сколько прошло с последнего глотка воды. Урон идёт не
    /// потоком, а глотками: тонущий должен успеть всплыть.
    f32 chokeTimer = 0.f;
};

/// Утомление: 0 — свеж, 1 — вымотан.
///
/// Выносливость одна отвечала и за «сейчас нет сил на рывок», и за
/// «я бегу третью минуту»: она полностью восстанавливалась за
/// десяток секунд, и никакой разницы между свежим героем и тем, кто
/// только что отбивался от стаи, не оставалось.
///
/// Утомление живёт дольше и работает иначе: оно не тратится, а
/// КОПИТСЯ — от бега и от ударов — и опускает потолок выносливости.
/// Вымотанный может бежать, но недалеко: его полоска не наполняется
/// доверху, пока он не отдохнёт.
struct Fatigue {
    f32 value     = 0.f;   ///< 0..1
    f32 restTimer = 0.f;   ///< сколько секунд без нагрузки
};

struct Attributes {
    i32 strength     = 10;
    i32 agility      = 10;
    i32 intelligence = 10;
    i32 endurance    = 10;
};

